package curl

import (
	"fmt"
	"net/http"
	"net/url"
	"path"
	"sort"
	"strconv"
	"strings"
	"sync"
	"time"
)

// cookieJar is the invocation's cookie store for -b and -c files. It keeps
// each cookie's attributes so the jar file round-trips in the Netscape format
// curl reads and writes; the owner's transport applies it per hop.
type cookieJar struct {
	mu      sync.Mutex
	cookies []storedCookie
}

type storedCookie struct {
	domain   string
	hostOnly bool
	path     string
	secure   bool
	httpOnly bool
	expires  time.Time
	name     string
	value    string
}

func (c storedCookie) key() string { return c.domain + "\x00" + c.path + "\x00" + c.name }

func (j *cookieJar) store(c storedCookie) {
	for i, existing := range j.cookies {
		if existing.key() == c.key() {
			j.cookies[i] = c
			return
		}
	}
	j.cookies = append(j.cookies, c)
}

func (j *cookieJar) SetCookies(u *url.URL, cookies []*http.Cookie) {
	j.mu.Lock()
	defer j.mu.Unlock()
	host := strings.ToLower(u.Hostname())
	for _, c := range cookies {
		stored := storedCookie{name: c.Name, value: c.Value, secure: c.Secure, httpOnly: c.HttpOnly, path: c.Path}
		if domain := strings.TrimPrefix(strings.ToLower(c.Domain), "."); domain != "" {
			if !domainMatch(host, domain) {
				continue
			}
			stored.domain = domain
		} else {
			stored.domain, stored.hostOnly = host, true
		}
		if stored.path == "" || !strings.HasPrefix(stored.path, "/") {
			stored.path = defaultPath(u.Path)
		}
		switch {
		case c.MaxAge < 0:
			stored.expires = time.Unix(1, 0)
		case c.MaxAge > 0:
			stored.expires = time.Now().Add(time.Duration(c.MaxAge) * time.Second)
		case !c.Expires.IsZero():
			stored.expires = c.Expires
		}
		j.store(stored)
	}
}

func (j *cookieJar) Cookies(u *url.URL) []*http.Cookie {
	j.mu.Lock()
	defer j.mu.Unlock()
	host := strings.ToLower(u.Hostname())
	now := time.Now()
	var out []*http.Cookie
	for _, c := range j.cookies {
		if !c.expires.IsZero() && !c.expires.After(now) {
			continue
		}
		if c.hostOnly && host != c.domain || !c.hostOnly && !domainMatch(host, c.domain) {
			continue
		}
		if !pathMatch(u.Path, c.path) || c.secure && u.Scheme != "https" {
			continue
		}
		out = append(out, &http.Cookie{Name: c.name, Value: c.value})
	}
	return out
}

func domainMatch(host, domain string) bool {
	return host == domain || strings.HasSuffix(host, "."+domain)
}

func pathMatch(requestPath, cookiePath string) bool {
	if requestPath == "" {
		requestPath = "/"
	}
	if requestPath == cookiePath {
		return true
	}
	return strings.HasPrefix(requestPath, cookiePath) && (strings.HasSuffix(cookiePath, "/") || requestPath[len(cookiePath)] == '/')
}

func defaultPath(requestPath string) string {
	if !strings.HasPrefix(requestPath, "/") || strings.Count(requestPath, "/") == 1 {
		return "/"
	}
	return path.Dir(requestPath)
}

const netscapeHeader = "# Netscape HTTP Cookie File\n# https://curl.se/docs/http-cookies.html\n# This file was generated by libcurl! Edit at your own risk.\n\n"

// load reads a Netscape cookie file; session cookies have expiry 0.
func (j *cookieJar) load(text string) error {
	j.mu.Lock()
	defer j.mu.Unlock()
	for number, line := range strings.Split(text, "\n") {
		line = strings.TrimRight(line, "\r")
		httpOnly := false
		if rest, ok := strings.CutPrefix(line, "#HttpOnly_"); ok {
			line, httpOnly = rest, true
		}
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Split(line, "\t")
		if len(fields) != 7 {
			return usage(fmt.Sprintf("line %d", number+1), "a Netscape cookie line of seven tab-separated fields")
		}
		expiry, err := strconv.ParseInt(fields[4], 10, 64)
		if err != nil {
			return usage(fields[4], "a numeric cookie expiry")
		}
		c := storedCookie{domain: strings.TrimPrefix(strings.ToLower(fields[0]), "."), hostOnly: fields[1] != "TRUE", path: fields[2],
			secure: fields[3] == "TRUE", httpOnly: httpOnly, name: fields[5], value: fields[6]}
		if expiry > 0 {
			c.expires = time.Unix(expiry, 0)
		}
		j.store(c)
	}
	return nil
}

// netscape writes the live cookies in curl's jar format, sorted for stable bytes.
func (j *cookieJar) netscape() []byte {
	j.mu.Lock()
	defer j.mu.Unlock()
	now := time.Now()
	lines := make([]string, 0, len(j.cookies))
	for _, c := range j.cookies {
		if !c.expires.IsZero() && !c.expires.After(now) {
			continue
		}
		domain := c.domain
		include := "FALSE"
		if !c.hostOnly {
			domain, include = "."+c.domain, "TRUE"
		}
		if c.httpOnly {
			domain = "#HttpOnly_" + domain
		}
		secure := "FALSE"
		if c.secure {
			secure = "TRUE"
		}
		var expiry int64
		if !c.expires.IsZero() {
			expiry = c.expires.Unix()
		}
		lines = append(lines, strings.Join([]string{domain, include, c.path, secure, strconv.FormatInt(expiry, 10), c.name, c.value}, "\t"))
	}
	sort.Strings(lines)
	var b strings.Builder
	b.WriteString(netscapeHeader)
	for _, line := range lines {
		b.WriteString(line + "\n")
	}
	return []byte(b.String())
}

// cookies builds the invocation jar from -b jar files and collects -b
// name=value pairs into one Cookie header.
func (inv *invocation) cookies() (*cookieJar, string, error) {
	jar := &cookieJar{}
	var pairs []string
	for _, value := range inv.opts.cookies {
		if strings.Contains(value, "=") {
			pairs = append(pairs, value)
			continue
		}
		text, err := inv.dests.ReadSource(inv.ctx, value)
		if err != nil {
			return nil, "", err
		}
		if err := jar.load(text); err != nil {
			return nil, "", err
		}
	}
	return jar, strings.Join(pairs, "; "), nil
}
