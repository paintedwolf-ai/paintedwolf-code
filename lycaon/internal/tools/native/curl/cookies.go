// cookieJar is the invocation's cookie store for -b and -c files. It delegates
// RFC 6265 selection, network Set-Cookie validation, and per-hop delivery
// filtering to httpcookies.Store, while round-tripping Netscape jar files.
type cookieJar struct {
	mu    sync.Mutex
	store *httpcookies.Store
}

func newCookieJar() *cookieJar {
	return &cookieJar{store: httpcookies.New(nil)}
}

// CookieStore returns the underlying RFC 6265 store for httpaction per-hop
// selection and secret authority screening.
func (j *cookieJar) CookieStore() *httpcookies.Store {
	j.mu.Lock()
	defer j.mu.Unlock()
	if j.store == nil {
		j.store = httpcookies.New(nil)
	}
	return j.store
}

func (j *cookieJar) SetCookies(u *url.URL, cookies []*http.Cookie) {
	j.CookieStore().SetCookies(u, cookies)
}

func (j *cookieJar) Cookies(u *url.URL) []*http.Cookie {
	return j.CookieStore().Cookies(u)
}

func isNetscapePublicSuffix(domain string) bool {
	suffix, _ := publicsuffix.PublicSuffix(domain)
	return suffix == domain
}

const netscapeHeader = "# Netscape HTTP Cookie File\n# https://curl.se/docs/http-cookies.html\n# This file was generated by libcurl! Edit at your own risk.\n\n"

// load reads a Netscape cookie file; session cookies have expiry 0.
func (j *cookieJar) load(text string) error {
	j.mu.Lock()
	defer j.mu.Unlock()
	if j.store == nil {
		j.store = httpcookies.New(nil)
	}
	now := time.Now().UTC()
	existing := j.store.Snapshot()
	for number, line := range strings.Split(text, "\n") {
		line = strings.TrimRight(line, "\r")
		httpOnly := false
		if rest, ok := strings.CutPrefix(line, "#HttpOnly_"); ok {
			line, httpOnly = rest, true
		}
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Split(line, "\t")
		if len(fields) != 7 {
			return usage(fmt.Sprintf("line %d", number+1), "a Netscape cookie line of seven tab-separated fields")
		}
		expiry, err := strconv.ParseInt(fields[4], 10, 64)
		if err != nil {
			return usage(fields[4], "a numeric cookie expiry")
		}
		domain := strings.TrimPrefix(strings.ToLower(strings.TrimSpace(fields[0])), ".")
		hostOnly := fields[1] != "TRUE"
		cookiePath := fields[2]
		if cookiePath == "" || !strings.HasPrefix(cookiePath, "/") {
			cookiePath = "/"
		}
		name, value := fields[5], fields[6]
		if domain == "" || name == "" {
			continue
		}
		if !hostOnly && (net.ParseIP(domain) != nil || isNetscapePublicSuffix(domain)) {
			continue
		}
		var expires time.Time
		expiredLine := false
		switch {
		case expiry < 0:
			expiredLine = true
		case expiry > 0:
			expires = time.Unix(expiry, 0).UTC()
			if !expires.After(now) {
				expiredLine = true
			}
		}
		kept := existing[:0]
		created := now.Add(time.Duration(number) * time.Nanosecond)
		for _, prev := range existing {
			if prev.Domain == domain && prev.Path == cookiePath && prev.Name == name {
				if !prev.Created.IsZero() {
					created = prev.Created
				}
				continue
			}
			kept = append(kept, prev)
		}
		existing = kept
		if expiredLine {
			continue
		}
		existing = append(existing, httpcookies.Cookie{
			Name:     name,
			Value:    value,
			Domain:   domain,
			HostOnly: hostOnly,
			Path:     cookiePath,
			Secure:   fields[3] == "TRUE",
			HTTPOnly: httpOnly,
			Expires:  expires,
			Created:  created,
		})
	}
	j.store = httpcookies.New(existing)
	return nil
}

// netscape writes the live cookies in curl's jar format, sorted for stable bytes.
func (j *cookieJar) netscape() []byte {
	live := j.CookieStore().Snapshot()
	lines := make([]string, 0, len(live))
	for _, c := range live {
		domain := c.Domain
		include := "FALSE"
		if !c.HostOnly {
			domain, include = "."+c.Domain, "TRUE"
		}
		if c.HTTPOnly {
			domain = "#HttpOnly_" + domain
		}
		secure := "FALSE"
		if c.Secure {
			secure = "TRUE"
		}
		var expiry int64
		if !c.Expires.IsZero() {
			expiry = c.Expires.Unix()
		}
		lines = append(lines, strings.Join([]string{domain, include, c.Path, secure, strconv.FormatInt(expiry, 10), c.Name, c.Value}, "\t"))
	}
	sort.Strings(lines)
	var b strings.Builder
	b.WriteString(netscapeHeader)
	for _, line := range lines {
		b.WriteString(line + "\n")
	}
	return []byte(b.String())
}

// cookies builds the invocation jar from -b jar files and collects -b
// name=value pairs into one Cookie header.
func (inv *invocation) cookies() (*cookieJar, string, error) {
	jar := newCookieJar()
	var pairs []string
	for _, value := range inv.opts.cookies {
		if strings.Contains(value, "=") {
			pairs = append(pairs, value)
			continue
		}
		text, err := inv.dests.ReadSource(inv.ctx, value)
		if err != nil {
			return nil, "", err
		}
		if err := jar.load(text); err != nil {
			return nil, "", err
		}
	}
	return jar, strings.Join(pairs, "; "), nil
}
