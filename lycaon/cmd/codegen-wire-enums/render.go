func eventPayloadType(payload string) (string, error) {
	const marker = "#/components/schemas/"
	idx := strings.LastIndex(payload, marker)
	if idx < 0 || idx+len(marker) == len(payload) {
		return "", fmt.Errorf("event payload ref %q must end in %s<Type>", payload, marker)
	}
	name := payload[idx+len(marker):]
	if strings.Contains(name, "/") {
		return "", fmt.Errorf("event payload ref %q must name one component schema", payload)
	}
	return name, nil
}

func renderEventPayloadsTS(e EnumDef) ([]byte, error) {
	var types []string
	seen := map[string]bool{}
	for _, topic := range e.Values {
		name, err := eventPayloadType(topic.Payload)
		if err != nil {
			return nil, fmt.Errorf("EventTopic %s: %w", topic.ID, err)
		}
		if !seen[name] {
			seen[name] = true
			types = append(types, name)
		}
	}
	sort.Strings(types)

	var b bytes.Buffer
	b.WriteString("// Code generated by codegen-wire-enums. DO NOT EDIT.\n")
	b.WriteString("// Source: docs/openapi/vocab/EventTopic.yaml\n\n")
	b.WriteString("import type {\n")
	for _, name := range types {
		fmt.Fprintf(&b, "  %s,\n", name)
	}
	b.WriteString("} from \"./types.ts\";\n\n")
	b.WriteString("/** Exhaustive topic-to-payload relation for EventHub SSE. */\n")
	b.WriteString("export type EventPayloadMap = {\n")
	for _, topic := range e.Values {
		name, _ := eventPayloadType(topic.Payload)
		fmt.Fprintf(&b, "  %s: %s;\n", topic.ID, name)
	}
	b.WriteString("};\n")
	return b.Bytes(), nil
}

func eventEnvelopeComponent(id string) string {
	var b strings.Builder
	b.WriteString("EventEnvelope")
	upper := true
	for _, r := range id {
		if r == '_' || r == '-' {
			upper = true
			continue
		}
		if upper {
			b.WriteRune(unicode.ToUpper(r))
			upper = false
		} else {
			b.WriteRune(r)
		}
	}
	return b.String()
}

