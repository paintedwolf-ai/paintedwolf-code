func renderOpenAPI(e EnumDef) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("# Code generated by codegen-wire-enums. DO NOT EDIT.\n")
	b.WriteString("# Source: docs/openapi/vocab/" + e.Name + ".yaml\n")
	b.WriteString("components:\n")
	b.WriteString("  schemas:\n")
	b.WriteString("    " + e.Name + ":\n")
	b.WriteString("      type: string\n")
	if d := strings.TrimSpace(e.Description); d != "" {
		b.WriteString("      description: ")
		b.WriteString(yamlScalar(d))
		b.WriteByte('\n')
	}
	b.WriteString("      enum:\n")
	for _, v := range e.Values {
		b.WriteString("        - ")
		b.WriteString(v.ID)
		b.WriteByte('\n')
	}
	return b.Bytes(), nil
}

func yamlScalar(s string) string {
	if strings.ContainsAny(s, ":#{}[],&*?|>!%@`\"'\n") {
		return fmt.Sprintf("%q", s)
	}
	return s
}

func renderGo(e EnumDef) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by codegen-wire-enums. DO NOT EDIT.\n")
	b.WriteString("// Source: docs/openapi/vocab/" + e.Name + ".yaml\n\n")
	b.WriteString("package api\n\n")
	if d := strings.TrimSpace(e.Description); d != "" {
		b.WriteString("// " + e.Name + " — " + d + "\n")
	} else {
		b.WriteString("// " + e.Name + " is a closed wire enum from docs/openapi/vocab.\n")
	}
	b.WriteString("type " + e.Name + " string\n\n")
	b.WriteString("const (\n")
	for _, v := range e.Values {
		name, err := e.constName(v)
		if err != nil {
			return nil, err
		}
		if c := v.Comment; c != "" {
			for _, line := range wrapComment(name+" "+c, 76) {
				fmt.Fprintf(&b, "\t// %s\n", line)
			}
		}
		fmt.Fprintf(&b, "\t%s %s = %q\n", name, e.Name, v.ID)
	}
	b.WriteString(")\n\n")
	allFn := "All" + e.Name + "Values"
	allVar := "all" + e.Name + "Values"
	fmt.Fprintf(&b, "var %s = []%s{\n", allVar, e.Name)
	for _, v := range e.Values {
		name, err := e.constName(v)
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "\t%s,\n", name)
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "// %s returns every %s in vocab order.\n", allFn, e.Name)
	fmt.Fprintf(&b, "func %s() []%s {\n", allFn, e.Name)
	fmt.Fprintf(&b, "\treturn append([]%s(nil), %s...)\n", e.Name, allVar)
	b.WriteString("}\n")
	deprecated := make([]EnumValue, 0)
	for _, value := range e.Values {
		if value.Deprecated {
			deprecated = append(deprecated, value)
		}
	}
	if len(deprecated) > 0 {
		fn := "Deprecated" + e.Name + "Successors"
		fmt.Fprintf(&b, "\n// %s returns successor mappings.\n", fn)
		fmt.Fprintf(&b, "func %s() map[%s]%s {\n", fn, e.Name, e.Name)
		fmt.Fprintf(&b, "\treturn map[%s]%s{\n", e.Name, e.Name)
		for _, value := range deprecated {
			name, err := e.constName(value)
			if err != nil {
				return nil, err
			}
			var successor EnumValue
			for _, candidate := range e.Values {
				if candidate.ID == value.Successor {
					successor = candidate
					break
				}
			}
			successorName, err := e.constName(successor)
			if err != nil {
				return nil, err
			}
			fmt.Fprintf(&b, "\t\t%s: %s,\n", name, successorName)
		}
		b.WriteString("\t}\n")
		b.WriteString("}\n")
	}
	if e.StateMachine != nil {
		renderGoStateMachine(&b, e)
	}
	if e.HTTPStatus {
		if err := renderGoHTTPStatus(&b, e); err != nil {
			return nil, err
		}
	}
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gofmt %s: %w\n%s", e.Name, err, b.String())
	}
	return formatted, nil
}

// renderGoHTTPStatus emits the one HTTP status each value is answered with,
// grouped by status so a response writer derives it from the code alone.
func renderGoHTTPStatus(b *bytes.Buffer, e EnumDef) error {
	byStatus := map[int][]string{}
	var statuses []int
	for _, v := range e.Values {
		name, err := e.constName(v)
		if err != nil {
			return err
		}
		if _, ok := byStatus[v.Status]; !ok {
			statuses = append(statuses, v.Status)
		}
		byStatus[v.Status] = append(byStatus[v.Status], name)
	}
	sort.Ints(statuses)
	fmt.Fprintf(b, "\n// HTTPStatus returns the HTTP status declared for c. A value outside the\n")
	fmt.Fprintf(b, "// vocabulary answers 500: no handler may invent a code.\n")
	fmt.Fprintf(b, "func (c %s) HTTPStatus() int {\n\tswitch c {\n", e.Name)
	for _, status := range statuses {
		fmt.Fprintf(b, "\tcase %s:\n\t\treturn %d\n", strings.Join(byStatus[status], ",\n\t\t"), status)
	}
	b.WriteString("\tdefault:\n\t\treturn 500\n\t}\n}\n")
	return nil
}

func renderGoStateMachine(b *bytes.Buffer, e EnumDef) {
	mapName := strings.ToLower(e.Name[:1]) + e.Name[1:] + "Transitions"
	initialName := strings.ToLower(e.Name[:1]) + e.Name[1:] + "Initial"
	fmt.Fprintf(b, "\nvar %s = map[%s]struct{}{\n", initialName, e.Name)
	for _, initial := range e.StateMachine.Initial {
		for _, candidate := range e.Values {
			if candidate.ID == initial {
				name, _ := e.constName(candidate)
				fmt.Fprintf(b, "\t%s: {},\n", name)
			}
		}
	}
	b.WriteString("}\n")
	fmt.Fprintf(b, "\nvar %s = map[%s]map[%s]struct{}{\n", mapName, e.Name, e.Name)
	for _, from := range e.Values {
		fromName, _ := e.constName(from)
		fmt.Fprintf(b, "\t%s: {\n", fromName)
		targets := append([]string(nil), e.StateMachine.Transitions[from.ID]...)
		sort.Strings(targets)
		for _, target := range targets {
			for _, candidate := range e.Values {
				if candidate.ID == target {
					name, _ := e.constName(candidate)
					fmt.Fprintf(b, "\t\t%s: {},\n", name)
				}
			}
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(b, "// IsValid%s reports whether value belongs to the state machine.\n", e.Name)
	fmt.Fprintf(b, "func IsValid%s(value %s) bool {\n", e.Name, e.Name)
	fmt.Fprintf(b, "\t_, ok := %s[value]\n\treturn ok\n}\n\n", mapName)
	fmt.Fprintf(b, "// IsInitial%s reports whether value can start the state machine.\n", e.Name)
	fmt.Fprintf(b, "func IsInitial%s(value %s) bool {\n", e.Name, e.Name)
	fmt.Fprintf(b, "\t_, ok := %s[value]\n\treturn ok\n}\n\n", initialName)
	fmt.Fprintf(b, "// CanTransition%s reports whether a state change is legal.\n", e.Name)
	fmt.Fprintf(b, "func CanTransition%s(from, to %s) bool {\n", e.Name, e.Name)
	fmt.Fprintf(b, "\tif from == to { return IsValid%s(from) }\n", e.Name)
	fmt.Fprintf(b, "\ttargets, ok := %s[from]\n", mapName)
	b.WriteString("\tif !ok { return false }\n\t_, ok = targets[to]\n\treturn ok\n}\n")
}

func renderJSONSchema(e EnumDef) ([]byte, error) {
	values := make([]string, 0, len(e.Values))
	for _, value := range e.Values {
		values = append(values, value.ID)
	}
	body, err := json.MarshalIndent(map[string]any{
		"$schema": "https://json-schema.org/draft/2020-12/schema",
		"title":   e.Name,
		"type":    "string",
		"enum":    values,
	}, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(body, '\n'), nil
}

// Clients reject stale snapshots but may skip intermediate server states.
func renderTSStateMachine(e EnumDef) []byte {
	name := e.Name
	constant := strings.ToUpper(snakeFile(name))
	var b bytes.Buffer
	b.WriteString("// Code generated by codegen-wire-enums. DO NOT EDIT.\n")
	b.WriteString("// Source: docs/openapi/vocab/" + name + ".yaml\n\n")
	fmt.Fprintf(&b, "import type { %s } from \"./types.ts\";\n\n", name)
	fmt.Fprintf(&b, "/** `satisfies` makes a value added to the vocab without transitions a type error. */\n")
	fmt.Fprintf(&b, "const %s_TRANSITIONS = {\n", constant)
	for _, from := range e.Values {
		fmt.Fprintf(&b, "  %s: [", from.ID)
		for i, target := range e.StateMachine.Transitions[from.ID] {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", target)
		}
		b.WriteString("],\n")
	}
	fmt.Fprintf(&b, "} as const satisfies Record<%s, readonly %s[]>;\n\n", name, name)
	fmt.Fprintf(&b, "/** States some transition leads to; the rest can only be a first state. */\n")
	fmt.Fprintf(&b, "const %s_ENTERABLE = new Set<%s>(\n", constant, name)
	fmt.Fprintf(&b, "  Object.values(%s_TRANSITIONS).flat(),\n", constant)
	b.WriteString(");\n\n")
	b.WriteString("/**\n")
	fmt.Fprintf(&b, " * Whether the machine can enter `value` from another state. False means an\n")
	fmt.Fprintf(&b, " * update carrying it arrived after the one that left it — a stale read.\n")
	b.WriteString(" */\n")
	fmt.Fprintf(&b, "export function isEnterable%s(value: %s): boolean {\n", name, name)
	fmt.Fprintf(&b, "  return %s_ENTERABLE.has(value);\n", constant)
	b.WriteString("}\n")
	return b.Bytes()
}

func renderSQLCheck(e EnumDef, source []byte) ([]byte, error) {
	startMarker := "-- codegen:" + e.Name + ":start"
	endMarker := "-- codegen:" + e.Name + ":end"
	start := bytes.Index(source, []byte(startMarker))
	end := bytes.Index(source, []byte(endMarker))
	if start < 0 || end < start {
		return nil, fmt.Errorf("%s SQL markers missing", e.Name)
	}
	lineEnd := bytes.IndexByte(source[start:], '\n')
	if lineEnd < 0 {
		return nil, fmt.Errorf("%s SQL start marker has no newline", e.Name)
	}
	lineEnd += start + 1
	values := make([]string, 0, len(e.Values))
	for _, value := range e.Values {
		values = append(values, fmt.Sprintf("'%s'", strings.ReplaceAll(value.ID, "'", "''")))
	}
	replacement := []byte("        status IN (" + strings.Join(values, ", ") + ")\n        ")
	out := append([]byte(nil), source[:lineEnd]...)
	out = append(out, replacement...)
	out = append(out, source[end:]...)
	return out, nil
}

// renderLabelsTS emits an exhaustive id-to-label table.
func renderLabelsTS(e EnumDef) ([]byte, error) {
	t := e.TSLabels
	var b bytes.Buffer
	b.WriteString("// Code generated by codegen-wire-enums. DO NOT EDIT.\n")
	b.WriteString("// Source: docs/openapi/vocab/" + e.Name + ".yaml\n\n")
	fmt.Fprintf(&b, "import type { %s } from %q;\n\n", e.Name, t.TypeImport)
	if t.Doc != "" {
		b.WriteString("/**\n")
		for _, line := range wrapComment(t.Doc, 76) {
			b.WriteString(" * " + line + "\n")
		}
		b.WriteString(" */\n")
	}
	fmt.Fprintf(&b, "export const %s = {\n", t.Const)
	for _, v := range e.Values {
		fmt.Fprintf(&b, "  %s: %q,\n", v.ID, v.Label)
	}
	fmt.Fprintf(&b, "} as const satisfies Record<%s, string>;\n", e.Name)
	return b.Bytes(), nil
}

func wrapComment(s string, width int) []string {
	var lines []string
	line := ""
	for _, word := range strings.Fields(s) {
		switch {
		case line == "":
			line = word
		case len(line)+1+len(word) <= width:
			line += " " + word
		default:
			lines = append(lines, line)
			line = word
		}
	}
	if line != "" {
		lines = append(lines, line)
	}
	return lines
}

