// Command codegen-native-tool-contracts emits native tool contracts.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/lycaon/lycaon/internal/nativemanifest"
)

func main() {
	outGo := flag.String("out-go", "", "output path for approval_tiers.generated.go")
	outContractGo := flag.String("out-contract-go", "", "output path for contracts.generated.go")
	check := flag.Bool("check", false, "exit 1 if any output is stale")
	flag.Parse()

	if *outGo == "" || *outContractGo == "" {
		fatal(fmt.Errorf("--out-go and --out-contract-go are required"))
	}

	cfg, err := nativemanifest.Load()
	if err != nil {
		fatal(err)
	}
	if err := cfg.ValidateToolContracts(); err != nil {
		fatal(err)
	}
	// Grant scopes may name native or approval-catalog tools.
	known := func(tool string) bool {
		if cfg.HasTool(tool) {
			return true
		}
		_, ok := cfg.ApprovalReversibility[tool]
		return ok
	}
	if err := cfg.ValidateGrantTargetScopes(known); err != nil {
		fatal(err)
	}
	if err := cfg.ValidateSpawnsProcess(known); err != nil {
		fatal(err)
	}
	if err := cfg.ValidateSurveyNeutral(known); err != nil {
		fatal(err)
	}
	if err := cfg.ValidateBoundedInProcess(known); err != nil {
		fatal(err)
	}
	if err := cfg.ValidateChunkablePayload(known); err != nil {
		fatal(err)
	}
	if err := cfg.ValidateDetachAfterBudget(known); err != nil {
		fatal(err)
	}
	if err := cfg.ValidateSessionScope(known); err != nil {
		fatal(err)
	}
	if err := cfg.ValidateSocketArg(known); err != nil {
		fatal(err)
	}
	if err := cfg.ValidateSecretReferenceSurface(known); err != nil {
		fatal(err)
	}
	if err := cfg.ValidateSecretReferenceArgs(known); err != nil {
		fatal(err)
	}
	if err := cfg.ValidateGrantIdentityNeutralArgs(known); err != nil {
		fatal(err)
	}
	// Path mutations include host-produced tools without model schemas.
	knownOrHostProduced := func(tool string) bool {
		return known(tool) || cfg.HasHostProducedTool(tool)
	}
	if err := cfg.ValidateMutatesPath(knownOrHostProduced); err != nil {
		fatal(err)
	}
	if err := cfg.ValidateMutatesContent(knownOrHostProduced); err != nil {
		fatal(err)
	}
	if err := cfg.ValidateMultiRoot(known); err != nil {
		fatal(err)
	}

	reversible, recoverable, irreversible := cfg.ToolsByTier()
	pathScoped := cfg.PathScopedTools()
	commandScoped := cfg.CommandScopedTools()
	processSpawning := cfg.ProcessSpawningTools()
	pathMutating := cfg.PathMutatingTools()
	goBody := renderGo(reversible, recoverable, irreversible, commandScoped, pathScoped, processSpawning, pathMutating)
	contractBody, err := renderToolContracts(cfg)
	if err != nil {
		fatal(err)
	}

	goBody, err = gofmtSource(goBody)
	if err != nil {
		fatal(err)
	}
	contractBody, err = gofmtSource(contractBody)
	if err != nil {
		fatal(err)
	}

	outputs := []struct {
		path string
		body []byte
		hint string
	}{
		{*outGo, goBody, "Go approval tiers"},
		{*outContractGo, contractBody, "Go tool contracts"},
	}

	if *check {
		for _, out := range outputs {
			existing, err := os.ReadFile(out.path) // #nosec G304 -- path from Taskfile
			if err != nil || string(existing) != string(out.body) {
				fatal(fmt.Errorf("stale %s (%s) — run ./task codegen:native-tool-contracts", out.path, out.hint))
			}
		}
		fmt.Fprintln(os.Stdout, "native tool contract codegen OK")
		return
	}

	for _, out := range outputs {
		if err := os.MkdirAll(filepath.Dir(out.path), 0o750); err != nil {
			fatal(err)
		}
		if err := os.WriteFile(out.path, out.body, 0o600); err != nil { // #nosec G306 -- generated artifact
			fatal(err)
		}
		fmt.Fprintln(os.Stdout, "wrote", out.path)
	}
}

// gofmtSource canonicalizes generated Go before drift checks.
func gofmtSource(body []byte) ([]byte, error) {
	formatted, err := format.Source(body)
	if err != nil {
		return nil, fmt.Errorf("format generated Go: %w", err)
	}
	return formatted, nil
}

func renderGo(reversible, recoverable, irreversible, commandScoped, pathScoped, processSpawning, pathMutating []string) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by codegen-native-tool-contracts. DO NOT EDIT.\n\n")
	b.WriteString("package settings\n\n")
	b.WriteString("// Approval tiers come from platform/tools/native-tools.yaml.\n")
	b.WriteString("var (\n")
	writeGoSlice(&b, "reversibleTools", reversible)
	writeGoSlice(&b, "recoverableTools", recoverable)
	writeGoSlice(&b, "irreversibleTools", irreversible)
	b.WriteString("\n")
	b.WriteString("\t// Command grants match exact structured arguments.\n")
	writeGoSlice(&b, "commandScopedTools", commandScoped)
	b.WriteString("\n")
	b.WriteString("\t// Path grants match path predicates.\n")
	writeGoSlice(&b, "pathScopedTools", pathScoped)
	b.WriteString("\n")
	b.WriteString("\t// processSpawningTools derive unobserved-channel facts from declared tool identity.\n")
	writeGoSlice(&b, "processSpawningTools", processSpawning)
	b.WriteString("\n")
	b.WriteString("\t// Declared write targets undergo protected-sink checks.\n")
	writeGoSlice(&b, "pathMutatingTools", pathMutating)
	b.WriteString(")\n")
	return b.Bytes()
}

func renderContractRow(b *bytes.Buffer, row nativemanifest.ToolContractRow) error {
	caps, err := capabilitiesConstant(row.Capabilities)
	if err != nil {
		return fmt.Errorf("%s: %w", row.Tool, err)
	}
	b.WriteString("\t")
	b.WriteString(strconv.Quote(row.Tool))
	b.WriteString(": {Owner: ")
	b.WriteString(strconv.Quote(row.Owner))
	b.WriteString(", Reversibility: ")
	b.WriteString(reversibilityConstant(row.Reversibility))
	b.WriteString(", Batch: ")
	b.WriteString(batchConstant(row.Batch))
	if row.BatchOptInArg != "" {
		b.WriteString(", BatchOptInArg: ")
		b.WriteString(strconv.Quote(row.BatchOptInArg))
	}
	if row.BatchConcurrencyLimit > 0 {
		b.WriteString(", BatchConcurrencyLimit: ")
		b.WriteString(strconv.Itoa(row.BatchConcurrencyLimit))
	}
	if row.BatchSerialWhenArg != "" {
		b.WriteString(", BatchSerialWhenArg: ")
		b.WriteString(strconv.Quote(row.BatchSerialWhenArg))
	}
	b.WriteString(", Order: ")
	b.WriteString(turnOrderConstant(row.TurnOrder))
	b.WriteString(", Lifecycle: ")
	b.WriteString(lifecycleConstant(row.Lifecycle))
	b.WriteString(", Capabilities: ")
	b.WriteString(caps)
	if row.ChunkablePayload {
		b.WriteString(", ChunkablePayload: true")
	}
	if row.SurveyNeutral {
		b.WriteString(", SurveyNeutral: true")
	}
	if row.DetachAfterBudget {
		b.WriteString(", DetachAfterBudget: true")
	}
	if row.SessionScope != "" {
		b.WriteString(", SessionScope: ")
		b.WriteString(sessionScopeConstant(row.SessionScope))
	}
	if row.SocketArg != "" {
		b.WriteString(", SocketArg: ")
		b.WriteString(strconv.Quote(row.SocketArg))
	}
	if row.BoundedInProcess {
		b.WriteString(", BoundedInProcess: true")
	}
	if row.SecretReferenceSurface != "" {
		b.WriteString(", SecretReferenceSurface: ")
		b.WriteString(secretSurfaceConstant(row.SecretReferenceSurface))
	}
	if len(row.SecretReferenceArgs) > 0 {
		b.WriteString(", SecretReferenceArgs: []string{")
		for i, arg := range row.SecretReferenceArgs {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(strconv.Quote(arg))
		}
		b.WriteString("}")
	}
	b.WriteString("},\n")
	return nil
}

func renderToolContracts(cfg nativemanifest.Config) ([]byte, error) {
	rows := cfg.ToolContractRows()
	var b bytes.Buffer
	b.WriteString("// Code generated by codegen-native-tool-contracts. DO NOT EDIT.\n\n")
	b.WriteString("package toolcontract\n\n")
	b.WriteString("var compiledContracts = map[string]Contract{\n")
	for _, row := range rows {
		if err := renderContractRow(&b, row); err != nil {
			return nil, err
		}
	}
	b.WriteString("}\n\n")
	b.WriteString("var compiledFamilies = map[string][]string{\n")
	for _, id := range cfg.FamilyIDs() {
		b.WriteString("\t")
		b.WriteString(strconv.Quote(id))
		b.WriteString(": {\n")
		for _, member := range cfg.FamilyMembers(id) {
			b.WriteString("\t\t")
			b.WriteString(strconv.Quote(member))
			b.WriteString(",\n")
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n\n")
	b.WriteString("var compiledCompanions = map[string][]string{\n")
	for _, tool := range cfg.CompanionTools() {
		b.WriteString("\t")
		b.WriteString(strconv.Quote(tool))
		b.WriteString(": {\n")
		for _, companion := range cfg.CompanionsOf(tool) {
			b.WriteString("\t\t")
			b.WriteString(strconv.Quote(companion))
			b.WriteString(",\n")
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n\n")
	b.WriteString("var compiledGrantIdentityNeutralArgs = map[string][]string{\n")
	for _, row := range cfg.GrantIdentityNeutralArgRows() {
		b.WriteString("\t")
		b.WriteString(strconv.Quote(row.Tool))
		b.WriteString(": {\n")
		for _, arg := range row.Args {
			b.WriteString("\t\t")
			b.WriteString(strconv.Quote(arg))
			b.WriteString(",\n")
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n\n")
	b.WriteString("var compiledResourceImplied = map[string][]string{\n")
	for _, fact := range cfg.ResourceImpliedFacts() {
		b.WriteString("\t")
		b.WriteString(strconv.Quote(fact))
		b.WriteString(": {\n")
		for _, tool := range cfg.ResourceImpliedTools(fact) {
			b.WriteString("\t\t")
			b.WriteString(strconv.Quote(tool))
			b.WriteString(",\n")
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n\n")
	b.WriteString("// Content mutations include host-produced tools without contract rows.\n")
	b.WriteString("var compiledMutatesContent = map[string]struct{}{\n")
	for _, tool := range cfg.ContentMutatingTools() {
		b.WriteString("\t")
		b.WriteString(strconv.Quote(tool))
		b.WriteString(": {},\n")
	}
	b.WriteString("}\n\n")
	b.WriteString("// Unlisted tools are unclassified; declared \"none\" tools have no path capability.\n")
	b.WriteString("var compiledMultiRoot = map[string]MultiRootCapability{\n")
	multiRoot := cfg.MultiRootTools()
	tools := make([]string, 0, len(multiRoot))
	for tool := range multiRoot {
		tools = append(tools, tool)
	}
	sort.Strings(tools)
	for _, tool := range tools {
		b.WriteString("\t")
		b.WriteString(strconv.Quote(tool))
		b.WriteString(": MultiRoot")
		b.WriteString(multiRootIdent(multiRoot[tool]))
		b.WriteString(",\n")
	}
	b.WriteString("}\n")
	return b.Bytes(), nil
}

// multiRootIdent maps a capability id to its Go constant suffix.
func multiRootIdent(capability string) string {
	switch capability {
	case "path":
		return "PathConsume"
	case "discovery":
		return "Discovery"
	case "command":
		return "Command"
	default:
		return "None"
	}
}

func capabilitiesConstant(values []string) (string, error) {
	if len(values) == 0 {
		return "0", nil
	}
	constants := make([]string, 0, len(values))
	for _, value := range values {
		ident, ok := capabilityIdent(value)
		if !ok {
			return "", fmt.Errorf("unknown execution capability %q", value)
		}
		constants = append(constants, ident)
	}
	return strings.Join(constants, " | "), nil
}

func capabilityIdent(value string) (string, bool) {
	switch value {
	case "host_resource":
		return "CapabilityHostResource", true
	case "socket":
		return "CapabilitySocket", true
	case "process_control":
		return "CapabilityProcessControl", true
	case "host_execution":
		return "CapabilityHostExecution", true
	case "direct_ip":
		return "CapabilityDirectIP", true
	case "local_listen":
		return "CapabilityLocalListen", true
	case "loopback_connect":
		return "CapabilityLoopbackConnect", true
	case "terminal_capture":
		return "CapabilityTerminalCapture", true
	case "write_root":
		return "CapabilityWriteRoot", true
	case "read_path":
		return "CapabilityReadPath", true
	case "package_execution":
		return "CapabilityPackageExecution", true
	case "file_change":
		return "CapabilityFileChange", true
	case "held_terminal_input":
		return "CapabilityHeldTerminalInput", true
	default:
		return "", false
	}
}

func reversibilityConstant(value string) string {
	switch value {
	case nativemanifest.TierRecoverable:
		return "ReversibilityRecoverable"
	case nativemanifest.TierIrreversible:
		return "ReversibilityIrreversible"
	default:
		return "ReversibilityReversible"
	}
}

func turnOrderConstant(value string) string {
	switch value {
	case nativemanifest.TurnOrderLate:
		return "TurnOrderLate"
	case nativemanifest.TurnOrderTerminal:
		return "TurnOrderTerminal"
	default:
		return "TurnOrderNormal"
	}
}

func batchConstant(value string) string {
	switch value {
	case nativemanifest.BatchShared:
		return "BatchShared"
	case nativemanifest.BatchSameTool:
		return "BatchSameTool"
	default:
		return "BatchSerial"
	}
}

func sessionScopeConstant(value string) string {
	if value == "worker_child" {
		return "SessionScopeWorkerChild"
	}
	return "SessionScopeAddressed"
}

func secretSurfaceConstant(value string) string {
	switch value {
	case nativemanifest.SecretSurfaceCommand:
		return "SecretSurfaceCommand"
	case nativemanifest.SecretSurfaceTerminal:
		return "SecretSurfaceTerminal"
	case nativemanifest.SecretSurfaceFile:
		return "SecretSurfaceFile"
	default:
		return "SecretSurfaceHTTPRequest"
	}
}

func lifecycleConstant(value string) string {
	switch value {
	case nativemanifest.LifecycleReadOnly:
		return "LifecycleReadOnly"
	case nativemanifest.LifecycleDBTransaction:
		return "LifecycleDBTransaction"
	case nativemanifest.LifecycleJournaledMutation:
		return "LifecycleJournaledMutation"
	case nativemanifest.LifecycleDurableJob:
		return "LifecycleDurableJob"
	case nativemanifest.LifecycleEffectAttempt:
		return "LifecycleEffectAttempt"
	default:
		return "LifecycleEphemeralControl"
	}
}

func writeGoSlice(b *bytes.Buffer, name string, tools []string) {
	b.WriteString("\t")
	b.WriteString(name)
	b.WriteString(" = []string{")
	if len(tools) == 0 {
		b.WriteString("}\n")
		return
	}
	b.WriteString("\n")
	for _, tool := range tools {
		b.WriteString("\t\t")
		b.WriteString(strconv.Quote(tool))
		b.WriteString(",\n")
	}
	b.WriteString("\t}\n")
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "error:", err)
	os.Exit(1)
}
