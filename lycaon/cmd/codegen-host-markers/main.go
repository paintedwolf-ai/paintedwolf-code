// Command codegen-host-markers generates transcript markers and worker statuses for Den.
package main

import (
	"flag"
	"fmt"
	"os"
	"strconv"
	"strings"

	"github.com/lycaon/lycaon/internal/hostmarker"
	"github.com/lycaon/lycaon/internal/session/workercompletion"
)

func main() {
	outTS := flag.String("out-ts", "", "output path for host-markers.generated.ts")
	check := flag.Bool("check", false, "exit 1 if the output is stale")
	flag.Parse()

	if *outTS == "" {
		fatal(fmt.Errorf("--out-ts is required"))
	}
	body := renderTypeScript()
	if *check {
		// #nosec G304 -- output path is an explicit command input.
		current, err := os.ReadFile(*outTS)
		if err != nil || string(current) != body {
			fatal(fmt.Errorf("%s is stale — run ./task codegen:host-markers", *outTS))
		}
		return
	}
	if err := os.WriteFile(*outTS, []byte(body), 0o600); err != nil { // #nosec G306 -- generated artifact
		fatal(err)
	}
}

func renderTypeScript() string {
	var b strings.Builder
	b.WriteString(`// Code generated by codegen-host-markers. DO NOT EDIT.
//
// Host transcript markers and worker statuses.
// Source: lycaon/internal/hostmarker and lycaon/internal/session/workercompletion.

`)
	for _, marker := range hostmarker.All() {
		fmt.Fprintf(&b, "export const %s = %s;\n", marker.Name, strconv.Quote(marker.Value))
	}

	b.WriteString("\n/** Accepted worker verdicts. */\n")
	b.WriteString("export const WORKER_LEG_STATUSES = [\n")
	for _, status := range workercompletion.LegStatuses() {
		fmt.Fprintf(&b, "  %s,\n", strconv.Quote(status))
	}
	b.WriteString("] as const;\n\n")
	b.WriteString("export type WorkerLegStatus = (typeof WORKER_LEG_STATUSES)[number];\n")

	return b.String()
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "codegen-host-markers:", err)
	os.Exit(1)
}
