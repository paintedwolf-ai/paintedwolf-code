// Command codegen-operations derives wire DTOs and operation bindings from OpenAPI.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

type operationSpec struct {
	OperationID  string `yaml:"operationId"`
	PersonAction string `yaml:"x-person-action"`
}

type document struct {
	Info struct {
		Version string `yaml:"version"`
	} `yaml:"info"`
	Paths map[string]map[string]yaml.Node `yaml:"paths"`
}

type operation struct {
	ID     string
	Method string
	Path   string
	Params []string
	// RecordsPersonAction is the operation's x-person-action declaration.
	RecordsPersonAction bool
}

var operationIDPattern = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9_]*$`)
var contractVersionPattern = regexp.MustCompile(`^[0-9]+\.[0-9]+\.[0-9]+$`)
var pathParamPattern = regexp.MustCompile(`\{([^{}]+)\}`)

func main() {
	repoRoot := flag.String("repo-root", ".", "repository root")
	outputRoot := flag.String("output-root", "", "staging output root")
	flag.Parse()

	root, err := filepath.Abs(*repoRoot)
	if err != nil {
		fatal(err)
	}
	input := filepath.Join(root, "docs", "openapi.yaml")
	if strings.TrimSpace(*outputRoot) == "" {
		fatal(fmt.Errorf("generation requires --output-root"))
	}
	outRoot, err := filepath.Abs(*outputRoot)
	if err != nil {
		fatal(err)
	}
	raw, err := os.ReadFile(input) // #nosec G304 -- repository path
	if err != nil {
		fatal(err)
	}
	var spec document
	if err := yaml.Unmarshal(raw, &spec); err != nil {
		fatal(err)
	}
	operations, err := loadOperations(spec)
	if err != nil {
		fatal(err)
	}
	contractVersion := strings.TrimSpace(spec.Info.Version)
	if !contractVersionPattern.MatchString(contractVersion) {
		fatal(fmt.Errorf("info.version %q must be MAJOR.MINOR.PATCH", contractVersion))
	}
	goBody, err := renderGo(operations, contractVersion)
	if err != nil {
		fatal(err)
	}
	dtoBody, err := renderGoDTOs(raw)
	if err != nil {
		fatal(err)
	}
	outputs := map[string][]byte{
		filepath.Join(outRoot, "lycaon", "pkg", "api", "types.generated.go"):           dtoBody,
		filepath.Join(outRoot, "lycaon", "internal", "api", "operations.generated.go"): goBody,
		filepath.Join(outRoot, "lycaon-den", "src", "api", "operations.generated.ts"):  renderTS(operations, contractVersion),
	}
	for path, body := range outputs {
		if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
			fatal(err)
		}
		if err := os.WriteFile(path, body, 0o600); err != nil { // #nosec G306 -- generated artifact
			fatal(err)
		}
		fmt.Fprintln(os.Stdout, "wrote", path)
	}
}

func loadOperations(spec document) ([]operation, error) {
	var out []operation
	seen := make(map[string]struct{})
	for path, item := range spec.Paths {
		for method, node := range item {
			method = strings.ToUpper(method)
			switch method {
			case "GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS":
			default:
				continue
			}
			var candidate operationSpec
			if err := node.Decode(&candidate); err != nil {
				return nil, fmt.Errorf("%s %s: %w", method, path, err)
			}
			id := strings.TrimSpace(candidate.OperationID)
			if !operationIDPattern.MatchString(id) {
				return nil, fmt.Errorf("%s %s needs a valid operationId", method, path)
			}
			if _, ok := seen[id]; ok {
				return nil, fmt.Errorf("duplicate operationId %q", id)
			}
			seen[id] = struct{}{}
			records, err := personActionDeclaration(method, candidate.PersonAction)
			if err != nil {
				return nil, fmt.Errorf("%s %s (%s): %w", method, path, id, err)
			}
			matches := pathParamPattern.FindAllStringSubmatch(path, -1)
			params := make([]string, 0, len(matches))
			for _, match := range matches {
				params = append(params, match[1])
			}
			out = append(out, operation{ID: id, Method: method, Path: path, Params: params, RecordsPersonAction: records})
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].ID < out[j].ID })
	return out, nil
}

// personActionDeclaration reads x-person-action. Every operation that can
// change state declares record or none; reads declare nothing.
func personActionDeclaration(method, declared string) (bool, error) {
	declared = strings.TrimSpace(declared)
	switch method {
	case "GET", "HEAD", "OPTIONS":
		if declared != "" {
			return false, fmt.Errorf("reads are never recorded; remove x-person-action")
		}
		return false, nil
	}
	switch declared {
	case "record":
		return true, nil
	case "none":
		return false, nil
	default:
		return false, fmt.Errorf("x-person-action must be record or none, got %q", declared)
	}
}

func renderGo(operations []operation, contractVersion string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by codegen-operations. DO NOT EDIT.\n\npackage api\n\n")
	b.WriteString("// contractVersion is the Host API contract this build serves (OpenAPI info.version).\n")
	fmt.Fprintf(&b, "const contractVersion = %q\n\n", contractVersion)
	b.WriteString("type generatedOperation struct {\n\tID string\n\tMethod string\n\tPath string\n")
	b.WriteString("\t// Params are the path parameter names in template order.\n\tParams []string\n")
	b.WriteString("\t// RecordsPersonAction records each completed call as a person action.\n\tRecordsPersonAction bool\n}\n\n")
	b.WriteString("var (\n")
	for _, op := range operations {
		fmt.Fprintf(&b, "\toperation%s = generatedOperation{ID: %q, Method: %q, Path: %q", exported(op.ID), op.ID, op.Method, op.Path)
		if len(op.Params) > 0 {
			fmt.Fprintf(&b, ", Params: %#v", op.Params)
		}
		if op.RecordsPersonAction {
			b.WriteString(", RecordsPersonAction: true")
		}
		b.WriteString("}\n")
	}
	b.WriteString(")\n")
	b.WriteString("\nvar allGeneratedOperations = []generatedOperation{\n")
	for _, op := range operations {
		fmt.Fprintf(&b, "\toperation%s,\n", exported(op.ID))
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func renderTS(operations []operation, contractVersion string) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by codegen-operations. DO NOT EDIT.\n\n")
	b.WriteString("import type { operations } from \"./types.ts\";\n\n")
	b.WriteString("/** Host API contract this client was built against (OpenAPI info.version). */\n")
	fmt.Fprintf(&b, "export const API_CONTRACT_VERSION = %q;\n\n", contractVersion)
	b.WriteString("export const API_OPERATIONS = {\n")
	for _, op := range operations {
		fmt.Fprintf(&b, "  %s: { method: %q, path: %q },\n", op.ID, op.Method, op.Path)
	}
	b.WriteString("} as const;\n\n")
	b.WriteString("export type OperationId = keyof typeof API_OPERATIONS;\n")
	b.WriteString("type SuccessStatus = 200 | 201 | 202 | 203 | 204 | 205 | 206;\n")
	b.WriteString("type ResponseBody<T> = T extends { content: { \"application/json\": infer Body } } ? Body : T extends { content?: never } ? void : unknown;\n")
	b.WriteString("export type OperationResponse<Id extends OperationId> = ResponseBody<operations[Id][\"responses\"][keyof operations[Id][\"responses\"] & SuccessStatus]>;\n")
	b.WriteString("export type OperationRequestBody<Id extends OperationId> = operations[Id] extends { requestBody: { content: { \"application/json\": infer Body } } } ? Body : never;\n")
	b.WriteString("export type OperationQuery<Id extends OperationId> = operations[Id] extends { parameters: { query?: infer Query } } ? Query : never;\n\n")
	b.WriteString("export type OperationPathParameters = {\n")
	for _, op := range operations {
		fmt.Fprintf(&b, "  %s: ", op.ID)
		if len(op.Params) == 0 {
			b.WriteString("Record<string, never>;\n")
			continue
		}
		b.WriteString("{ ")
		for _, param := range op.Params {
			fmt.Fprintf(&b, "%s: string | number; ", tsProperty(param))
		}
		b.WriteString("};\n")
	}
	b.WriteString("};\n\n")
	b.WriteString("export function operationPath<Id extends OperationId>(id: Id, ...args: keyof OperationPathParameters[Id] extends never ? [] : [OperationPathParameters[Id]]): string {\n")
	b.WriteString("  const params = (args[0] ?? {}) as Record<string, string | number>;\n")
	b.WriteString("  return API_OPERATIONS[id].path.replace(/\\{([^{}]+)\\}/g, (_match, key: string) => {\n")
	b.WriteString("    const value = params[key];\n")
	b.WriteString("    if (value == null) throw new Error(`Missing path parameter ${key} for ${id}`);\n")
	b.WriteString("    return encodeURIComponent(String(value));\n")
	b.WriteString("  });\n}\n\n")
	b.WriteString("function operationPattern(template: string): RegExp {\n")
	b.WriteString("  const escaped = template.replace(/[.*+?^${}()|[\\]\\\\]/g, \"\\\\$&\");\n")
	b.WriteString("  return new RegExp(`^${escaped.replace(/\\\\\\{[^{}]+\\\\\\}/g, \"[^/]+\")}$`);\n}\n\n")
	b.WriteString("export function assertOperationRequest(path: string, method: string): void {\n")
	b.WriteString("  const pathname = path.split(\"?\", 1)[0] ?? path;\n")
	b.WriteString("  const normalizedMethod = method.toUpperCase();\n")
	b.WriteString("  for (const operation of Object.values(API_OPERATIONS)) {\n")
	b.WriteString("    if (operation.method === normalizedMethod && operationPattern(operation.path).test(pathname)) return;\n")
	b.WriteString("  }\n")
	b.WriteString("  throw new Error(`Unknown API operation ${normalizedMethod} ${pathname}`);\n}\n")
	return b.Bytes()
}

func exported(id string) string {
	return strings.ToUpper(id[:1]) + id[1:]
}

func tsProperty(value string) string {
	if operationIDPattern.MatchString(value) {
		return value
	}
	return fmt.Sprintf("%q", value)
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
