package main

import (
	"fmt"
	"sort"
	"strings"
)

const generatedNotice = "Generated by cmd/codegen-dependency-inventory from dependencies/. Do not edit by hand."

var (
	urgencyRank   = map[string]int{"critical": 0, "high": 1, "moderate": 2, "low": 3}
	updateDisplay = map[string]string{
		updatesHold: "Held", updatesNoMajor: "No majors", updatesPatchOnly: "Patches only",
	}
)

func renderInventory(p *policy, sections []section, snap snapshot) []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "<!-- %s -->\n\n# %s\n\n", generatedNotice, p.Title)
	writeProse(&b, p.intro)
	fmt.Fprintf(&b, "Pinned values are read from the tree when this page is generated. "+
		"Upstream values come from `dependencies/upstream.json`, last refreshed on **%s**. "+
		"The dependency inventory workflow regenerates this page after dependency changes land on main "+
		"and refreshes upstream weekly. This page highlights priority updates and upgrade constraints; "+
		"the complete policy and pin sources are linked below.\n\n---\n\n", snap.Fetched)
	renderBehind(&b, sections, snap)
	b.WriteString("## Rating vectors\n\n")
	writeProse(&b, p.ratings)
	renderQuadrants(&b, p.Quadrants, sections)
	renderConstraints(&b, sections, snap)
	renderInventorySources(&b, sections)
	b.WriteString("## Operational runbooks\n\n")
	writeProse(&b, p.runbooks)
	return []byte(strings.TrimRight(b.String(), "\n") + "\n")
}

func writeProse(b *strings.Builder, text string) {
	if text = strings.TrimSpace(text); text != "" {
		b.WriteString(text + "\n\n")
	}
}

func renderBehind(b *strings.Builder, sections []section, snap snapshot) {
	type entry struct {
		row   row
		pairs [][2]string
	}
	var entries []entry
	for _, s := range sections {
		for _, r := range s.rows {
			if r.Urgency != "critical" && r.Urgency != "high" {
				continue
			}
			if pairs := r.behind(snap); len(pairs) > 0 {
				entries = append(entries, entry{r, pairs})
			}
		}
	}
	sort.SliceStable(entries, func(i, j int) bool {
		return urgencyRank[entries[i].row.Urgency] < urgencyRank[entries[j].row.Urgency]
	})
	b.WriteString("## Behind upstream\n\nCritical- and high-urgency entries whose pinned version trails the upstream snapshot.\n\n")
	if len(entries) == 0 {
		b.WriteString("None as of the snapshot.\n\n---\n\n")
		return
	}
	for _, e := range entries {
		var pairs []string
		for _, p := range e.pairs {
			pairs = append(pairs, fmt.Sprintf("`%s` → `%s`", display(p[0]), display(p[1])))
		}
		fmt.Fprintf(b, "* **%s** (%s): %s\n", e.row.name, e.row.Urgency, strings.Join(pairs, "; "))
	}
	b.WriteString("\n---\n\n")
}

func renderQuadrants(b *strings.Builder, stances quadrantStances, sections []section) {
	quadrants := []struct {
		title, stance     string
		urgent, expensive bool
		members           int
	}{
		{title: "High urgency, high friction", stance: stances.HighUrgencyHighFriction, urgent: true, expensive: true},
		{title: "High urgency, low or moderate friction", stance: stances.HighUrgencyLowFriction, urgent: true},
		{title: "Low or moderate urgency, high friction", stance: stances.LowUrgencyHighFriction, expensive: true},
		{title: "Low or moderate urgency, low or moderate friction", stance: stances.LowUrgencyLowFriction},
	}
	for _, s := range sections {
		for _, r := range s.rows {
			if r.Urgency == "" || r.Friction == "" {
				continue
			}
			urgent := r.Urgency == "critical" || r.Urgency == "high"
			for i := range quadrants {
				if quadrants[i].urgent == urgent && quadrants[i].expensive == (r.Friction == "high") {
					quadrants[i].members++
				}
			}
		}
	}
	b.WriteString("## Quadrants\n\nAn entry counts as high urgency when rated Critical or High, and as high friction when rated High. " +
		"Entries missing either rating are not placed.\n\n| Quadrant | Stance | Entries |\n|---|---|---|\n")
	for _, q := range quadrants {
		fmt.Fprintf(b, "| **%s** | %s | %d |\n", q.title, cell(q.stance), q.members)
	}
	b.WriteString("\n---\n\n")
}

func renderTable(b *strings.Builder, rows []row, snap snapshot, dependabot bool) {
	header := "| Name | Pinned | Upstream | Urgency | Friction |"
	if dependabot {
		header += " Dependabot |"
	}
	header += " Notes |\n"
	b.WriteString(header + strings.Repeat("|---", strings.Count(header, "|")-1) + "|\n")
	for _, r := range rows {
		cells := []string{r.name, pinnedCell(r), upstreamCell(r, snap), rated(r.Urgency), rated(r.Friction)}
		if dependabot {
			cells = append(cells, dependabotCell(r))
		}
		cells = append(cells, cell(r.notes()))
		b.WriteString("| " + strings.Join(cells, " | ") + " |\n")
	}
	b.WriteString("\n")
}

func dependabotCell(r row) string {
	if r.dependency == "" {
		return "—"
	}
	return updateDisplay[r.Updates]
}

func pinnedCell(r row) string {
	if len(r.pins) == 0 {
		return "—"
	}
	parts := make([]string, 0, len(r.pins))
	for _, p := range r.pins {
		parts = append(parts, labeled(p.label, "`"+display(p.text)+"`"))
	}
	out := strings.Join(parts, "<br>")
	if r.pinNote != "" {
		out += " " + r.pinNote
	}
	return out
}

func upstreamCell(r row, snap snapshot) string {
	var parts []string
	for i, ref := range r.upstream {
		up := snap.Versions[ref.key]
		switch {
		case up == "":
			parts = append(parts, labeled(ref.label, "not refreshed"))
		case sameVersion(up, r.comparablePin(i)):
			parts = append(parts, labeled(ref.label, "current"))
		default:
			parts = append(parts, labeled(ref.label, "`"+display(up)+"`"))
		}
	}
	return strings.Join(parts, "<br>")
}

func labeled(label, text string) string {
	if label == "" {
		return text
	}
	return label + " " + text
}

func rated(level string) string {
	if level == "" {
		return ""
	}
	return "**" + strings.ToUpper(level[:1]) + level[1:] + "**"
}

// cell flattens prose into one table cell; blank lines become line breaks.
func cell(text string) string {
	paragraphs := strings.Split(strings.TrimSpace(text), "\n\n")
	for i, p := range paragraphs {
		paragraphs[i] = strings.Join(strings.Fields(p), " ")
	}
	return strings.ReplaceAll(strings.Join(paragraphs, "<br>"), "|", `\|`)
}

func renderDependabot(p *policy, sections []section) []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n# Regenerate with ./task codegen:dependency-inventory.\nversion: 2\nupdates:\n", generatedNotice)
	d := p.Dependabot
	for _, e := range d.Extra {
		writeDependabotEntry(&b, d, e, nil)
	}
	for _, s := range sections {
		m := s.cfg.Manifest
		if m == nil || m.DependabotGroup == "" {
			continue
		}
		e := dependabotEntry{Ecosystem: m.Kind, Directories: []string{manifestDirectory(m.Path)}, Group: m.DependabotGroup}
		writeDependabotEntry(&b, d, e, s.rows)
	}
	return []byte(strings.TrimRight(b.String(), "\n") + "\n")
}

func writeDependabotEntry(b *strings.Builder, d dependabotConfig, e dependabotEntry, rows []row) {
	fmt.Fprintf(b, "  - package-ecosystem: %s\n    directories:\n", e.Ecosystem)
	for _, directory := range e.Directories {
		fmt.Fprintf(b, "      - %q\n", directory)
	}
	fmt.Fprintf(b, "    schedule:\n      interval: %s\n", d.Interval)
	if d.CooldownDays > 0 {
		fmt.Fprintf(b, "    cooldown:\n      default-days: %d\n", d.CooldownDays)
	}
	if e.Group != "" {
		fmt.Fprintf(b, "    groups:\n      %s:\n        applies-to: version-updates\n        patterns:\n          - \"*\"\n        update-types:\n          - minor\n          - patch\n", e.Group)
	}
	ignored := make([]row, 0, len(rows))
	for _, r := range rows {
		if r.Updates != "" && r.dependency != "" {
			ignored = append(ignored, r)
		}
	}
	sort.Slice(ignored, func(i, j int) bool { return ignored[i].dependency < ignored[j].dependency })
	if len(ignored) > 0 {
		b.WriteString("    ignore:\n")
	}
	for _, r := range ignored {
		fmt.Fprintf(b, "      - dependency-name: %q\n", r.dependency)
		switch r.Updates {
		case updatesNoMajor:
			b.WriteString("        update-types:\n          - version-update:semver-major\n")
		case updatesPatchOnly:
			b.WriteString("        update-types:\n          - version-update:semver-major\n          - version-update:semver-minor\n")
		}
	}
	b.WriteString("\n")
}
