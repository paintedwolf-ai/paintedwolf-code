type readerFactCatalogFile struct {
	Facts            []prompts.ReaderFactScalarSpec `yaml:"facts"`
	Families         []prompts.ReaderFactFamilySpec `yaml:"families"`
	ReservedPrefixes []string                       `yaml:"reserved_prefixes"`
}

func loadReaderFactCatalog(moduleRoot string) (readerFactCatalogFile, error) {
	path := filepath.Join(moduleRoot, "config", filepath.FromSlash(config.ReaderFacts.String()))
	raw, err := os.ReadFile(path) // #nosec G304 -- resolved from moduleRoot
	if err != nil {
		return readerFactCatalogFile{}, fmt.Errorf("read %s: %w", path, err)
	}
	var doc readerFactCatalogFile
	dec := yaml.NewDecoder(bytes.NewReader(raw))
	dec.KnownFields(true)
	if err := dec.Decode(&doc); err != nil {
		return readerFactCatalogFile{}, fmt.Errorf("parse %s: %w", path, err)
	}
	seen := make(map[string]bool, len(doc.Facts))
	for _, f := range doc.Facts {
		name := strings.TrimSpace(f.Name)
		if name == "" {
			return readerFactCatalogFile{}, fmt.Errorf("%s: empty scalar fact name", path)
		}
		if seen[name] {
			return readerFactCatalogFile{}, fmt.Errorf("%s: duplicate scalar fact %q", path, name)
		}
		seen[name] = true
		switch f.Type {
		case "bool", "int", "string", "[]string", "[]map[string]any":
		default:
			return readerFactCatalogFile{}, fmt.Errorf("%s: unsupported type %q on %q", path, f.Type, name)
		}
	}
	for i := range doc.Families {
		fam := &doc.Families[i]
		prefix, nested, err := parseFamilyPattern(fam.Pattern)
		if err != nil {
			return readerFactCatalogFile{}, fmt.Errorf("%s: %w", path, err)
		}
		fam.Prefix = prefix
		fam.Nested = nested
	}
	return doc, nil
}

func parseFamilyPattern(pattern string) (prefix string, nested bool, err error) {
	idx := strings.IndexByte(pattern, '{')
	if idx <= 0 || !strings.HasSuffix(pattern, "}") {
		return "", false, fmt.Errorf("invalid family pattern %q", pattern)
	}
	head := pattern[:idx]
	if strings.HasSuffix(head, ".") {
		return strings.TrimSuffix(head, "."), true, nil
	}
	return head, false, nil
}

func syncReaderFacts(moduleRoot, readerFactsPath string, check bool) error {
	wantReaderFacts, err := generateReaderFactsSource(moduleRoot)
	if err != nil {
		return err
	}
	if check {
		haveReaderFacts, err := os.ReadFile(readerFactsPath) // #nosec G304 -- path under moduleRoot
		if err != nil || !bytes.Equal(haveReaderFacts, wantReaderFacts) {
			return fmt.Errorf("stale %s — run ./task codegen:guidance-registry", readerFactsPath)
		}
		return nil
	}
	if err := os.WriteFile(readerFactsPath, wantReaderFacts, 0o600); err != nil {
		return err
	}
	fmt.Println("wrote", readerFactsPath)
	return nil
}

func generateReaderFactsSource(moduleRoot string) ([]byte, error) {
	doc, err := loadReaderFactCatalog(moduleRoot)
	if err != nil {
		return nil, err
	}
	facts := slices.Clone(doc.Facts)
	sort.Slice(facts, func(i, j int) bool { return facts[i].Name < facts[j].Name })

	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/codegen-guidance-registry from platform/host/reader-facts.yaml; DO NOT EDIT.\n\n")
	b.WriteString("package prompts\n\n")
	b.WriteString("import (\n\t\"maps\"\n\t\"strings\"\n)\n\n")

	b.WriteString("var declaredReaderFactScalarNames = []string{\n")
	for _, f := range facts {
		fmt.Fprintf(&b, "\t%q,\n", f.Name)
	}
	b.WriteString("}\n\n")

	b.WriteString("var declaredReaderFactScalars = map[string]ReaderFactScalarSpec{\n")
	for _, f := range facts {
		fmt.Fprintf(&b, "\t%q: {Name: %q, Type: %q, States: %q},\n", f.Name, f.Name, f.Type, f.States)
	}
	b.WriteString("}\n\n")

	b.WriteString("var readerFactFamilies = []ReaderFactFamilySpec{\n")
	for _, fam := range doc.Families {
		fmt.Fprintf(&b, "\t{Pattern: %q, Prefix: %q, Nested: %v, Over: %q, Type: %q, States: %q},\n",
			fam.Pattern, fam.Prefix, fam.Nested, fam.Over, fam.Type, fam.States)
	}
	b.WriteString("}\n\n")

	b.WriteString("var reservedReaderFactPrefixes = []string{\n")
	for _, p := range doc.ReservedPrefixes {
		fmt.Fprintf(&b, "\t%q,\n", p)
	}
	b.WriteString("}\n\n")

	b.WriteString("// ReaderFacts holds the typed values produced by Reader.Facts().\n")
	b.WriteString("type ReaderFacts struct {\n")
	for _, f := range facts {
		fmt.Fprintf(&b, "\t%s %s\n", goFieldNameForFact(f.Name), f.Type)
	}
	for _, fam := range doc.Families {
		fmt.Fprintf(&b, "\t%s map[string]%s\n", goFieldNameForFact(fam.Prefix), fam.Type)
	}
	b.WriteString("}\n\n")

	b.WriteString("// Map flattens the typed reader facts and family maps into a template variable map.\n")
	b.WriteString("func (f ReaderFacts) Map() map[string]any {\n")
	fmt.Fprintf(&b, "\tout := make(map[string]any, %d+len(f.ProfileHas)+len(f.AgentHasSkill))\n", len(facts)+len(doc.Families))
	for _, f := range facts {
		field := "f." + goFieldNameForFact(f.Name)
		if parts := strings.Split(f.Name, "."); len(parts) == 2 {
			fmt.Fprintf(&b, "\tout[%q] = map[string]any{%q: %s}\n", parts[0], parts[1], field)
			continue
		}
		switch f.Type {
		case "[]string":
			fmt.Fprintf(&b, "\tif %s != nil {\n\t\tout[%q] = append([]string(nil), %s...)\n\t} else {\n\t\tout[%q] = []string(nil)\n\t}\n", field, f.Name, field, f.Name)
		default:
			fmt.Fprintf(&b, "\tout[%q] = %s\n", f.Name, field)
		}
	}
	for _, fam := range doc.Families {
		field := "f." + goFieldNameForFact(fam.Prefix)
		if fam.Nested {
			fmt.Fprintf(&b, "\tif %s != nil {\n\t\tout[%q] = maps.Clone(%s)\n\t} else {\n\t\tout[%q] = map[string]%s{}\n\t}\n",
				field, fam.Prefix, field, fam.Prefix, fam.Type)
		} else {
			fmt.Fprintf(&b, "\tfor k, v := range %s {\n\t\tout[%q+k] = v\n\t}\n", field, fam.Prefix)
		}
	}
	b.WriteString("\treturn out\n}\n\n")

	b.WriteString(`func withAgentSkillMembershipVars(data map[string]any) map[string]any {
	out := make(map[string]any, len(data)+8)
	for key, value := range data {
		if strings.HasPrefix(key, agentSkillMembershipPrefix) {
			out[key] = false
		} else {
			out[key] = value
		}
	}
	for _, key := range stockSkillMembershipKeys() {
		if _, ok := out[key]; !ok {
			out[key] = false
		}
	}
	for _, skill := range agentSkillViewsFromVars(data) {
		if key := agentSkillMembershipKey(skill.Name); key != "" {
			out[key] = true
		}
	}
	return out
}
`)

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated reader facts: %w\n%s", err, b.String())
	}
	return formatted, nil
}

func goFieldNameForFact(name string) string {
	raw := strings.FieldsFunc(name, func(r rune) bool {
		return r == '_' || r == '.'
	})
	var b strings.Builder
	for _, part := range raw {
		switch part {
		case "id":
			b.WriteString("ID")
		case "ip":
			b.WriteString("IP")
		case "mib":
			b.WriteString("MiB")
		case "http":
			b.WriteString("HTTP")
		case "url":
			b.WriteString("URL")
		default:
			if len(part) > 0 {
				b.WriteString(strings.ToUpper(part[:1]) + part[1:])
			}
		}
	}
	return b.String()
}
