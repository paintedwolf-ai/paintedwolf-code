func writeGeneratedFile(path string, body string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(body), 0o600) // #nosec G306 -- generated artifact
}

func dedupeSorted(items []string) []string {
	if len(items) == 0 {
		return items
	}
	out := items[:1]
	for i := 1; i < len(items); i++ {
		if items[i] != out[len(out)-1] {
			out = append(out, items[i])
		}
	}
	return out
}

func wrapYAMLBlock(text string, indent int) string {
	prefix := strings.Repeat(" ", indent)
	words := strings.Fields(text)
	if len(words) == 0 {
		return prefix + "\n"
	}
	var lines []string
	var current strings.Builder
	for _, word := range words {
		if current.Len() == 0 {
			current.WriteString(word)
			continue
		}
		candidate := current.String() + " " + word
		if len(candidate) > 72 {
			lines = append(lines, prefix+current.String())
			current.Reset()
			current.WriteString(word)
		} else {
			current.Reset()
			current.WriteString(candidate)
		}
	}
	if current.Len() > 0 {
		lines = append(lines, prefix+current.String())
	}
	return strings.Join(lines, "\n") + "\n"
}

func yamlQuote(s string) string {
	return fmt.Sprintf("%q", s)
}

func checkGeneratedPacks(paths modulePaths) error {
	tmpRoot, err := os.MkdirTemp("", "detection-packs-check-*")
	if err != nil {
		return err
	}
	defer func() { _ = os.RemoveAll(tmpRoot) }()

	bridges, err := generateStructuredCloudPacks(paths.structuredCloudMap, tmpRoot)
	if err != nil {
		return err
	}
	for _, bridge := range bridges {
		if err := compareGeneratedPackTree(paths.root, tmpRoot, bridge.PackID); err != nil {
			return err
		}
	}
	fmt.Println("detection packs codegen OK")
	return nil
}

func compareGeneratedPackTree(committedRoot, generatedRoot, id string) error {
	relPack := filepath.Join("config", "packs", "painted-wolf", "security", "host", "detection-packs", id)
	committedPack := filepath.Join(committedRoot, relPack)
	generatedPack := filepath.Join(generatedRoot, relPack)
	committedFiles, err := listGeneratedFiles(committedPack)
	if err != nil {
		return err
	}
	generatedFiles, err := listGeneratedFiles(generatedPack)
	if err != nil {
		return err
	}
	if strings.Join(committedFiles, "\x00") != strings.Join(generatedFiles, "\x00") {
		return fmt.Errorf("stale %s file set — run ./task codegen:detection-packs", relPack)
	}
	for _, rel := range generatedFiles {
		if err := compareFiles(filepath.Join(committedPack, rel), filepath.Join(generatedPack, rel)); err != nil {
			return fmt.Errorf("stale %s — run ./task codegen:detection-packs: %w", filepath.Join(relPack, rel), err)
		}
	}
	return nil
}

func listGeneratedFiles(root string) ([]string, error) {
	var files []string
	err := filepath.WalkDir(root, func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			return nil
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		files = append(files, rel)
		return nil
	})
	sort.Strings(files)
	return files, err
}

func compareFiles(wantPath, gotPath string) error {
	want, err := os.ReadFile(wantPath) // #nosec G304 -- committed pack path
	if err != nil {
		return fmt.Errorf("read committed: %w", err)
	}
	got, err := os.ReadFile(gotPath) // #nosec G304 -- temp generated path
	if err != nil {
		return fmt.Errorf("read generated: %w", err)
	}
	if !bytes.Equal(want, got) {
		return fmt.Errorf("byte mismatch")
	}
	return nil
}
