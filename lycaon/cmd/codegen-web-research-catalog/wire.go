func webSearchProviderConstName(id string) (string, error) {
	id = strings.TrimSpace(id)
	if id == "" {
		return "", fmt.Errorf("empty provider id")
	}
	suffix, ok := webSearchProviderConstOverrides[id]
	if !ok {
		suffix = snakeToExported(id)
	}
	if suffix == "" {
		return "", fmt.Errorf("cannot derive const name for provider id %q", id)
	}
	return "WebSearchProvider" + suffix, nil
}

func snakeToExported(id string) string {
	parts := strings.Split(id, "_")
	var b strings.Builder
	for _, p := range parts {
		p = strings.TrimSpace(p)
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]))
		if len(p) > 1 {
			b.WriteString(p[1:])
		}
	}
	return b.String()
}
