package main

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
)

// wireProviderIDs returns catalog ids plus the built-in direct mode id, in
// catalog order then "direct".
func wireProviderIDs(cat providerCatalog) []string {
	ids := append([]string(nil), cat.IDs()...)
	ids = append(ids, "direct")
	return ids
}

func renderOpenAPIEnum(cat providerCatalog) ([]byte, error) {
	if cat == nil || len(cat.Entries()) == 0 {
		return nil, fmt.Errorf("catalog has no providers")
	}
	var b bytes.Buffer
	b.WriteString("# Code generated by codegen-web-research-catalog. DO NOT EDIT.\n")
	b.WriteString("# Source: lycaon/config/packs/painted-wolf/web-research/host/web-research-providers.yaml (+ built-in direct).\n")
	b.WriteString("components:\n")
	b.WriteString("  schemas:\n")
	b.WriteString("    WebSearchProvider:\n")
	b.WriteString("      type: string\n")
	b.WriteString("      enum:\n")
	for _, id := range wireProviderIDs(cat) {
		b.WriteString("        - ")
		b.WriteString(id)
		b.WriteByte('\n')
	}
	return b.Bytes(), nil
}

func renderGoProviderIDs(cat providerCatalog) ([]byte, error) {
	if cat == nil || len(cat.Entries()) == 0 {
		return nil, fmt.Errorf("catalog has no providers")
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by codegen-web-research-catalog. DO NOT EDIT.\n\n")
	b.WriteString("package api\n\n")
	b.WriteString("// WebSearchProvider identifies a web_search backend on the wire.\n")
	b.WriteString("type WebSearchProvider string\n\n")
	b.WriteString("const (\n")
	for _, id := range wireProviderIDs(cat) {
		name, err := webSearchProviderConstName(id)
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "\t%s WebSearchProvider = %q\n", name, id)
	}
	b.WriteString(")\n")
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gofmt generated provider ids: %w\n%s", err, b.String())
	}
	return formatted, nil
}

