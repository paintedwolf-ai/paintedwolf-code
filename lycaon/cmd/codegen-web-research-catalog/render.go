package main

import (
	"bytes"
	"fmt"
	"strings"

	"github.com/lycaon/lycaon/internal/webresearch"
)

type providerCatalog interface {
	Entries() []webresearch.CatalogEntry
	IDs() []string
}

func renderTypeScript(cat providerCatalog) ([]byte, error) {
	if cat == nil {
		return nil, fmt.Errorf("catalog has no providers")
	}
	providers := cat.Entries()
	if len(providers) == 0 {
		return nil, fmt.Errorf("catalog has no providers")
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by codegen-web-research-catalog. DO NOT EDIT.\n\n")

	kinds := uniqueKinds(providers)
	b.WriteString("export type WebResearchProviderKind = ")
	b.WriteString(tsStringUnion(kinds))
	b.WriteString(";\n\n")

	b.WriteString("export type WebResearchProviderId = ")
	ids := make([]string, len(providers))
	for i, entry := range providers {
		ids[i] = entry.ID
	}
	b.WriteString(tsStringUnion(ids))
	b.WriteString(";\n\n")

	b.WriteString(`export interface WebResearchCatalogExtraField {
  name: string;
  env: string;
  label: string;
}

export type WebResearchProviderRole = "results" | "seeds";

export interface WebResearchCatalogEntry {
  id: WebResearchProviderId;
  kind: WebResearchProviderKind;
  label: string;
  hint: string;
  test_query: string;
  roles: readonly WebResearchProviderRole[];
  default_enabled?: boolean;
  credential_slot?: string;
  optional_credential_slot?: string;
  api_key_env?: string;
  default_endpoint?: string;
  allow_private_endpoint?: boolean;
  extra_fields?: readonly WebResearchCatalogExtraField[];
}

`)

	b.WriteString("export const WEB_RESEARCH_CATALOG: readonly WebResearchCatalogEntry[] = [\n")
	for _, entry := range providers {
		b.WriteString("  ")
		b.WriteString(renderEntry(entry))
		b.WriteString(",\n")
	}
	b.WriteString("] as const;\n\n")

	b.WriteString("export const WEB_RESEARCH_PROVIDER_IDS: readonly WebResearchProviderId[] = [\n")
	for _, id := range ids {
		b.WriteString("  ")
		b.WriteString(tsQuote(id))
		b.WriteString(",\n")
	}
	b.WriteString("] as const;\n\n")

	b.WriteString(`const CATALOG_BY_ID: Record<WebResearchProviderId, WebResearchCatalogEntry> = {
`)
	for _, entry := range providers {
		b.WriteString("  ")
		b.WriteString(tsQuote(entry.ID))
		b.WriteString(": ")
		b.WriteString(renderEntry(entry))
		b.WriteString(",\n")
	}
	b.WriteString(`};

export function catalogEntry(id: WebResearchProviderId): WebResearchCatalogEntry {
  return CATALOG_BY_ID[id];
}

export function catalogByKind(kind: WebResearchProviderKind): WebResearchCatalogEntry[] {
  return WEB_RESEARCH_CATALOG.filter((entry) => entry.kind === kind);
}
`)

	return b.Bytes(), nil
}

func renderEntry(entry webresearch.CatalogEntry) string {
	var fields []string
	fields = append(fields, "id: "+tsQuote(entry.ID))
	fields = append(fields, "kind: "+tsQuote(string(entry.Kind)))
	fields = append(fields, "label: "+tsQuote(entry.Label))
	fields = append(fields, "hint: "+tsQuote(entry.Hint))
	fields = append(fields, "test_query: "+tsQuote(entry.TestQuery))
	roles := entry.RolesOrDefault()
	roleParts := make([]string, len(roles))
	for i, role := range roles {
		roleParts[i] = tsQuote(string(role))
	}
	fields = append(fields, "roles: ["+strings.Join(roleParts, ", ")+"]")
	if entry.DefaultEnabled {
		fields = append(fields, "default_enabled: true")
	}
	if entry.CredentialSlot != "" {
		fields = append(fields, "credential_slot: "+tsQuote(entry.CredentialSlot))
	}
	if entry.OptionalCredentialSlot != "" {
		fields = append(fields, "optional_credential_slot: "+tsQuote(entry.OptionalCredentialSlot))
	}
	if entry.APIKeyEnv != "" {
		fields = append(fields, "api_key_env: "+tsQuote(entry.APIKeyEnv))
	}
	if entry.DefaultEndpoint != "" {
		fields = append(fields, "default_endpoint: "+tsQuote(entry.DefaultEndpoint))
	}
	if entry.AllowPrivateEndpoint {
		fields = append(fields, "allow_private_endpoint: true")
	}
	if len(entry.ExtraFields) > 0 {
		var extras []string
		for _, f := range entry.ExtraFields {
			extras = append(extras, fmt.Sprintf("{ name: %s, env: %s, label: %s }", tsQuote(f.Name), tsQuote(f.Env), tsQuote(f.Label)))
		}
		fields = append(fields, "extra_fields: ["+strings.Join(extras, ", ")+"]")
	}
	return "{\n    " + strings.Join(fields, ",\n    ") + ",\n  }"
}

func uniqueKinds(entries []webresearch.CatalogEntry) []string {
	seen := make(map[string]struct{})
	var out []string
	for _, entry := range entries {
		k := string(entry.Kind)
		if _, ok := seen[k]; ok {
			continue
		}
		seen[k] = struct{}{}
		out = append(out, k)
	}
	return out
}

func tsStringUnion(values []string) string {
	if len(values) == 0 {
		return "never"
	}
	parts := make([]string, len(values))
	for i, v := range values {
		parts[i] = tsQuote(v)
	}
	return strings.Join(parts, " | ")
}

func tsQuote(s string) string {
	return `"` + strings.ReplaceAll(s, `"`, `\"`) + `"`
}
