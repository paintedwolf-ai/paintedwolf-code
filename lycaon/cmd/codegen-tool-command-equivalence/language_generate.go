func generateLanguageCatalog(root string, check bool) error {
	catalog, err := loadLanguageCatalog(root)
	if err != nil {
		return err
	}
	data, err := json.Marshal(catalog)
	if err != nil {
		return fmt.Errorf("marshal language catalog: %w", err)
	}
	source := "// Code generated by cmd/codegen-tool-command-equivalence. DO NOT EDIT.\n\npackage toolcontract\n\n// LanguageV1 returns a detached contract snapshot; it does not activate execution.\nfunc LanguageV1() (LanguageCatalog,error) { return DecodeLanguageCatalog([]byte(languageV1JSON)) }\n\nconst languageV1JSON = " + strconv.Quote(string(data)) + "\n"
	formatted, err := format.Source([]byte(source))
	if err != nil {
		return fmt.Errorf("format language catalog: %w", err)
	}
	output := filepath.Join(root, "internal", "toolcontract", "language_catalog.generated.go")
	if err := assertPathUnderRoot(output, root); err != nil {
		return err
	}
	return writeOrCheck(output, formatted, check)
}

func loadLanguageCatalog(root string) (toolcontract.LanguageCatalog, error) {
	catalog := toolcontract.LanguageCatalog{Version: 1, Contracts: map[string]json.RawMessage{}}
	paths, err := filepath.Glob(filepath.Join(root, "config", "packs", "painted-wolf", "platform", "tools", "command-language-v1", "*.json"))
	if err != nil {
		return catalog, fmt.Errorf("list language sources: %w", err)
	}
	if len(paths) == 0 {
		return catalog, fmt.Errorf("missing version1 language sources")
	}
	for _, path := range paths {
		data, err := readTrackedFile(path)
		if err != nil {
			return catalog, err
		}
		if filepath.Base(path) == "language.json" {
			if err := toolcontract.DecodeLanguageJSON(data, &catalog.Language); err != nil {
				return catalog, fmt.Errorf("decode language specification: %w", err)
			}
			continue
		}
		var fragment struct {
			Commands []toolcontract.CommandSpecification `json:"commands"`
			Tools    []toolcontract.ToolDisposition      `json:"tools"`
		}
		var keys map[string]json.RawMessage
		if err := json.Unmarshal(data, &keys); err != nil {
			return catalog, fmt.Errorf("decode catalog object: %w", err)
		}
		if keys["commands"] == nil && keys["tools"] == nil {
			catalog.Contracts[strings.TrimSuffix(filepath.Base(path), ".json")] = data
			continue
		}
		if err := toolcontract.DecodeLanguageJSON(data, &fragment); err != nil {
			return catalog, fmt.Errorf("decode %s: %w", filepath.Base(path), err)
		}
		catalog.Commands = append(catalog.Commands, fragment.Commands...)
		catalog.Tools = append(catalog.Tools, fragment.Tools...)

	}
	sort.Slice(catalog.Commands, func(i, j int) bool { return catalog.Commands[i].Name < catalog.Commands[j].Name })
	if len(paths) != len(catalog.Language.Sources) {
		return catalog, fmt.Errorf("language source inventory differs")
	}
	sourceNames := map[string]bool{}
	for _, name := range catalog.Language.Sources {
		if name != filepath.Base(name) || sourceNames[name] {
			return catalog, fmt.Errorf("invalid/duplicate source inventory entry %q", name)
		}
		sourceNames[name] = true
		if err := assertRegularFile(filepath.Join(filepath.Dir(paths[0]), name)); err != nil {
			return catalog, fmt.Errorf("required language source %s: %w", name, err)
		}
	}
	if err := validateLanguageCatalog(root, catalog); err != nil {
		return catalog, err
	}
	catalog.Fixtures = languageFormFixtures(catalog)
	if err := validateLanguageFixtures(catalog); err != nil {
		return catalog, err
	}
	return catalog, nil
}

func validateLanguageCatalog(root string, c toolcontract.LanguageCatalog) error {
	if c.Language.Version != 1 || len(c.Language.Limits) == 0 || len(c.Language.SchemaCopy) < 2500 || len(c.Language.SchemaCopy) > 4000 {
		return fmt.Errorf("language version, limits or compact schema copy invalid")
	}
	limits := map[string]bool{}
	for _, limit := range c.Language.Limits {
		if limit.ID == "" || limit.Maximum <= 0 || limit.Unit == "" || limit.Scope == "" || limit.Overflow == "" || limits[limit.ID] {
			return fmt.Errorf("invalid/duplicate language limit %q", limit.ID)
		}
		limits[limit.ID] = true
	}
	owners := map[string]bool{}
	for _, row := range c.Tools {
		owners[row.Owner] = true
	}
	names := map[string]bool{}
	for _, command := range c.Commands {
		if names[command.Name] || command.Name == "" || command.Argv == "" || command.Owner == "" || command.Encoding == "" || len(command.Statuses) == 0 || len(command.Effects) == 0 {
			return fmt.Errorf("invalid/duplicate command %q", command.Name)
		}
		if !owners[command.Owner] {
			return fmt.Errorf("unknown subsystem owner for %s", command.Name)
		}
		if len(command.FixtureIDs) < 2 || command.Unsupported.Kind == "" || command.Unsupported.Code == "" || len(command.Unsupported.Words) == 0 || command.Unsupported.Fallback {
			return fmt.Errorf("incomplete rejection fixture for %s", command.Name)
		}
		names[command.Name] = true
		for _, effect := range command.Effects {
			if effect.Mode == "" || effect.Requires == nil {
				return fmt.Errorf("missing typed effect mode/set for %s", command.Name)
			}
		}
		for _, alias := range command.Aliases {
			if names[alias] {
				return fmt.Errorf("duplicate command alias %q", alias)
			}
			names[alias] = true
		}
		flags := map[string]bool{}
		for _, form := range command.Forms {
			if len(form.Spellings) == 0 || form.Arity < -2 || form.Arity > 2 || form.FixtureID == "" || form.Consumption == "" || (form.Arity >= 0 && len(form.SampleValues) != form.Arity) {
				return fmt.Errorf("invalid option form for %s", command.Name)
			}
			if form.Shorthand != "" {
				if (form.Shorthand != "numeric" && form.Shorthand != "word") || form.Arity != 1 || flags[form.Scope+":shorthand"] {
					return fmt.Errorf("invalid %s option shorthand", command.Name)
				}
				flags[form.Scope+":shorthand"] = true
			}
			for _, flag := range form.Spellings {
				if flags[form.Scope+":"+flag] {
					return fmt.Errorf("duplicate %s option %s", command.Name, flag)
				}
				flags[form.Scope+":"+flag] = true
			}
		}
		for _, limit := range command.Limits {
			if !limits[limit] {
				return fmt.Errorf("%s unknown limit %s", command.Name, limit)
			}
		}
		refs := append([]string{command.Reuse.Implementation}, command.Reuse.Tests...)
		for _, ref := range refs {
			if err := validateLanguageReference(root, ref); err != nil {
				return err
			}
		}
	}
	commandOwners := map[string]string{}
	for _, command := range c.Commands {
		commandOwners[command.Name] = command.Owner
	}
	for _, row := range c.Tools {
		if row.CommandForms == nil || (row.Command != "" && len(row.CommandForms) == 0) {
			return fmt.Errorf("missing typed command references for %s", row.Tool)
		}
		seen := map[string]bool{}
		for _, form := range row.CommandForms {
			if seen[form] || commandOwners[form] == "" {
				return fmt.Errorf("invalid/duplicate operation command reference %s: %s", row.Tool, form)
			}
			if commandOwners[form] != row.Owner {
				return fmt.Errorf("operation command owner differs for %s", row.Tool)
			}
			seen[form] = true
		}
	}
	if len(c.Language.RequiredCommands) != len(c.Commands) {
		return fmt.Errorf("required command inventory differs")
	}
	required := map[string]bool{}
	for _, name := range c.Language.RequiredCommands {
		if required[name] {
			return fmt.Errorf("duplicate required command %s", name)
		}
		required[name] = true
		if !names[name] {
			return fmt.Errorf("missing required command %s", name)
		}
	}
	if len(c.Contracts) != len(c.Language.RequiredContracts) {
		return fmt.Errorf("required semantic contracts differ")
	}
	for name, key := range c.Language.RequiredContracts {
		var content map[string]json.RawMessage
		if err := json.Unmarshal(c.Contracts[name], &content); err != nil || len(content[key]) == 0 || len(content) != 1 {
			return fmt.Errorf("missing/invalid semantic contract %s", name)
		}
	}
	return validateToolDispositions(root, c.Tools)
}

func validateLanguageReference(root, ref string) error {
	if filepath.IsAbs(ref) || strings.Contains(ref, "..") || ref == "" {
		return fmt.Errorf("language reference must be repository relative: %q", ref)
	}
	path := filepath.Join(root, "..", filepath.FromSlash(ref))
	if err := assertRegularFile(path); err != nil {
		return fmt.Errorf("language reference %s: %w", ref, err)
	}
	return nil
}

func validateToolDispositions(root string, rows []toolcontract.ToolDisposition) error {
	data, err := readTrackedFile(filepath.Join(root, "config", "packs", "painted-wolf", "platform", "tools", "native-tools.yaml"))
	if err != nil {
		return err
	}
	var manifest struct {
		Owner     map[string]string `yaml:"owner"`
		Lifecycle map[string]string `yaml:"lifecycle"`
	}
	if err := yaml.Unmarshal(data, &manifest); err != nil {
		return fmt.Errorf("decode stock manifest: %w", err)
	}
	seen := map[string]bool{}
	for _, row := range rows {
		if seen[row.Tool] || row.Disposition == "" || row.Owner != manifest.Owner[row.Tool] || row.Lifecycle != manifest.Lifecycle[row.Tool] {
			return fmt.Errorf("stock disposition mismatch: %s", row.Tool)
		}
		seen[row.Tool] = true
		if err := validateLanguageReference(root, row.Source); err != nil {
			return err
		}
		if err := validateLanguageReference(root, row.Test); err != nil {
			return err
		}
	}
	if len(seen) != len(manifest.Owner) {
		return fmt.Errorf("stock dispositions cover %d of %d tools", len(seen), len(manifest.Owner))
	}
	return nil
}

func languageFormFixtures(c toolcontract.LanguageCatalog) []toolcontract.FormFixture {
	var fixtures []toolcontract.FormFixture
	for _, command := range c.Commands {
		fixtures = append(fixtures, toolcontract.FormFixture{ID: strings.ReplaceAll(command.Name, " ", "-") + "-operands-valid", Kind: "illustrative-program", Command: command.Name, Definition: command.Example})
		fixtures = append(fixtures, toolcontract.FormFixture{ID: command.FixtureIDs[1], Kind: command.Unsupported.Kind, Command: command.Name, Words: command.Unsupported.Words, Diagnostic: command.Unsupported.Code})
		for _, form := range command.Forms {
			for i, flag := range form.Spellings {
				id := form.FixtureID
				if i > 0 {
					id += "-alias-" + strconv.Itoa(i)
				}
				words := []string{flag}
				words = append(words, form.SampleValues...)
				fixtures = append(fixtures, toolcontract.FormFixture{ID: id, Kind: "option-fragment", Command: command.Name, Words: words, ExpectedForm: form.Spellings[0], Arity: form.Arity})
			}
			if form.Arity > 0 {
				fixtures = append(fixtures, toolcontract.FormFixture{ID: form.FixtureID + "-missing-value", Kind: "option-fragment", Command: command.Name, Words: []string{form.Spellings[0]}, Diagnostic: "COMMAND_OPERAND_INVALID"})
			}
		}
	}
	for _, limit := range c.Language.Limits {
		fixtures = append(fixtures, toolcontract.FormFixture{ID: limit.ID + "-at", Kind: "budget-transition", Limit: limit.ID, Value: limit.Maximum, ExpectedForm: "within-ceiling"})
		fixtures = append(fixtures, toolcontract.FormFixture{ID: limit.ID + "-over", Kind: "budget-transition", Limit: limit.ID, Value: limit.Maximum + 1, ExpectedForm: limit.Overflow, Diagnostic: limit.Exceeded})
	}
	return fixtures
}

func validateLanguageFixtures(c toolcontract.LanguageCatalog) error {
	seen := map[string]bool{}
	for _, fixture := range c.Fixtures {
		if fixture.ID == "" || seen[fixture.ID] {
			return fmt.Errorf("duplicate/empty language fixture %s", fixture.ID)
		}
		seen[fixture.ID] = true
	}
	for _, command := range c.Commands {
		for _, id := range command.FixtureIDs {
			if !seen[id] {
				return fmt.Errorf("missing referenced fixture %s", id)
			}
		}
	}
	for _, limit := range c.Language.Limits {
		for _, id := range limit.BoundaryFixtures {
			if !seen[id] {
				return fmt.Errorf("missing boundary fixture %s", id)
			}
		}
	}
	return nil
}
