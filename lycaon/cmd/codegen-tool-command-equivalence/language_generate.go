func generateLanguageCatalog(root string, check bool) error {
 catalog,err:=loadLanguageCatalog(root)
 if err!=nil { return err }
 data,err:=json.Marshal(catalog)
 if err!=nil { return fmt.Errorf("marshal language catalog: %w",err) }
 source:="// Code generated by cmd/codegen-tool-command-equivalence. DO NOT EDIT.\n\npackage commandsurface\n\n// LanguageV1 returns a detached contract snapshot; it does not activate execution.\nfunc LanguageV1() (LanguageCatalog,error) { return DecodeLanguageCatalog([]byte(languageV1JSON)) }\n\nconst languageV1JSON = "+strconv.Quote(string(data))+"\n"
 formatted,err:=format.Source([]byte(source))
 if err!=nil { return fmt.Errorf("format language catalog: %w",err) }
 output:=filepath.Join(root,"internal","commandsurface","language_catalog.generated.go")
 if err:=assertPathUnderRoot(output,root);err!=nil { return err }
 return writeOrCheck(output,formatted,check)
}

func loadLanguageCatalog(root string) (commandsurface.LanguageCatalog,error) {
 catalog:=commandsurface.LanguageCatalog{Version:1,Contracts:map[string]json.RawMessage{}}
 paths,err:=filepath.Glob(filepath.Join(root,"config","packs","painted-wolf","platform","tools","command-language-v1","*.json"))
 if err!=nil { return catalog,fmt.Errorf("list language sources: %w",err) }
 if len(paths)==0 { return catalog,fmt.Errorf("missing version1 language sources") }
 for _,path:=range paths {
  data,err:=readTrackedFile(path)
  if err!=nil { return catalog,err }
  if filepath.Base(path)=="language.json" {
   if err:=json.Unmarshal(data,&catalog.Language);err!=nil { return catalog,fmt.Errorf("decode language specification: %w",err) }
   continue
  }
  var fragment struct { Commands []commandsurface.CommandSpecification `json:"commands"`; Tools []commandsurface.ToolDisposition `json:"tools"` }
  if err:=json.Unmarshal(data,&fragment);err!=nil { return catalog,fmt.Errorf("decode %s: %w",filepath.Base(path),err) }
  catalog.Commands=append(catalog.Commands,fragment.Commands...)
  catalog.Tools=append(catalog.Tools,fragment.Tools...)
  if fragment.Commands==nil && fragment.Tools==nil { catalog.Contracts[strings.TrimSuffix(filepath.Base(path),".json")]=data }
 }
 sort.Slice(catalog.Commands,func(i,j int)bool{return catalog.Commands[i].Name<catalog.Commands[j].Name})
 if err:=validateLanguageCatalog(root,catalog);err!=nil { return catalog,err }
 catalog.Fixtures=languageFormFixtures(catalog)
 return catalog,nil
}

func validateLanguageCatalog(root string,c commandsurface.LanguageCatalog) error {
 if c.Language.Version!=1 || len(c.Language.Limits)==0 || len(c.Language.SchemaCopy)<2500 || len(c.Language.SchemaCopy)>4000 { return fmt.Errorf("language version, limits or compact schema copy invalid") }
 limits:=map[string]bool{}
 for _,limit:=range c.Language.Limits {
  if limit.ID=="" || limit.Maximum<=0 || limit.Unit=="" || limit.Scope=="" || limit.Overflow=="" || limits[limit.ID] { return fmt.Errorf("invalid/duplicate language limit %q",limit.ID) }
  limits[limit.ID]=true
 }
 names:=map[string]bool{}
 for _,command:=range c.Commands {
  if names[command.Name] || command.Name=="" || command.Argv=="" || command.Owner=="" || command.Encoding=="" || len(command.Statuses)==0 || len(command.Effects)==0 { return fmt.Errorf("invalid/duplicate command %q",command.Name) }
  names[command.Name]=true
  for _,alias:=range command.Aliases { if names[alias] { return fmt.Errorf("duplicate command alias %q",alias) };names[alias]=true }
  flags:=map[string]bool{}
  for _,form:=range command.Forms {
   if len(form.Spellings)==0 || form.Arity < -1 || form.Arity>2 || form.FixtureID=="" { return fmt.Errorf("invalid option form for %s",command.Name) }
   for _,flag:=range form.Spellings { if flags[form.Scope+":"+flag] { return fmt.Errorf("duplicate %s option %s",command.Name,flag) }; flags[form.Scope+":"+flag]=true }
  }
  for _,limit:=range command.Limits { if !limits[limit] { return fmt.Errorf("%s unknown limit %s",command.Name,limit) } }
  refs:=append([]string{command.Reuse.Implementation},command.Reuse.Tests...)
  for _,ref:=range refs { if err:=validateLanguageReference(root,ref);err!=nil { return err } }
 }
 return validateToolDispositions(root,c.Tools)
}

func validateLanguageReference(root,ref string) error {
 if filepath.IsAbs(ref) || strings.Contains(ref,"..") || ref=="" { return fmt.Errorf("language reference must be repository relative: %q",ref) }
 path:=filepath.Join(root,"..",filepath.FromSlash(ref))
 if err:=assertRegularFile(path);err!=nil { return fmt.Errorf("language reference %s: %w",ref,err) }
 return nil
}

func validateToolDispositions(root string,rows []commandsurface.ToolDisposition) error {
 data,err:=readTrackedFile(filepath.Join(root,"config","packs","painted-wolf","platform","tools","native-tools.yaml"))
 if err!=nil { return err }
 var manifest struct { Owner map[string]string `yaml:"owner"`; Lifecycle map[string]string `yaml:"lifecycle"` }
 if err:=yaml.Unmarshal(data,&manifest);err!=nil { return fmt.Errorf("decode stock manifest: %w",err) }
 seen:=map[string]bool{}
 for _,row:=range rows {
  if seen[row.Tool] || row.Disposition=="" || row.Owner!=manifest.Owner[row.Tool] || row.Lifecycle!=manifest.Lifecycle[row.Tool] { return fmt.Errorf("stock disposition mismatch: %s",row.Tool) }
  seen[row.Tool]=true
  if err:=validateLanguageReference(root,row.Source);err!=nil { return err }
  if err:=validateLanguageReference(root,row.Test);err!=nil { return err }
 }
 if len(seen)!=len(manifest.Owner) { return fmt.Errorf("stock dispositions cover %d of %d tools",len(seen),len(manifest.Owner)) }
 return nil
}

func languageFormFixtures(c commandsurface.LanguageCatalog) []commandsurface.FormFixture {
 var fixtures []commandsurface.FormFixture
 for _,command:=range c.Commands {
  fixtures=append(fixtures,commandsurface.FormFixture{ID:strings.ReplaceAll(command.Name," ","-")+"-operands-valid",Kind:"documented-program",Command:command.Name})
  fixtures=append(fixtures,commandsurface.FormFixture{ID:strings.ReplaceAll(command.Name," ","-")+"-option-invalid",Kind:"option-fragment",Command:command.Name,Words:[]string{"--not-a-version-1-option"},Diagnostic:"COMMAND_OPTION_UNSUPPORTED"})
  for _,form:=range command.Forms {
   for i,flag:=range form.Spellings {
    id:=form.FixtureID
    if i>0 { id+="-alias-"+strconv.Itoa(i) }
    words:=[]string{flag}
    for range max(form.Arity,0) { words=append(words,"<"+form.ValueRole+">") }
    fixtures=append(fixtures,commandsurface.FormFixture{ID:id,Kind:"option-fragment",Command:command.Name,Words:words,ExpectedForm:form.Spellings[0],Arity:form.Arity})
   }
   if form.Arity>0 { fixtures=append(fixtures,commandsurface.FormFixture{ID:form.FixtureID+"-missing-value",Kind:"option-fragment",Command:command.Name,Words:[]string{form.Spellings[0]},Diagnostic:"COMMAND_OPERAND_INVALID"}) }
  }
 }
 for _,limit:=range c.Language.Limits {
  fixtures=append(fixtures,commandsurface.FormFixture{ID:limit.ID+"-at",Kind:"budget-transition",Limit:limit.ID,Value:limit.Maximum,ExpectedForm:"within-ceiling"})
  fixtures=append(fixtures,commandsurface.FormFixture{ID:limit.ID+"-over",Kind:"budget-transition",Limit:limit.ID,Value:limit.Maximum+1,ExpectedForm:limit.Overflow,Diagnostic:limit.Exceeded})
 }
 return fixtures
}
