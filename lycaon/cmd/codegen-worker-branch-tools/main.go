// Command codegen-worker-branch-tools emits the host set of tools that require a
// private write-worker branch before Run (native-tools.yaml requires_worker_branch).
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strconv"

	"github.com/lycaon/lycaon/internal/nativemanifest"
)

func main() {
	if err := run(os.Args[1:], os.Stdout); err != nil {
		fatal(err)
	}
}

func run(args []string, stdout io.Writer) error {
	flags := flag.NewFlagSet("codegen-worker-branch-tools", flag.ContinueOnError)
	flags.SetOutput(io.Discard)
	outGo := flags.String("out-go", "", "output path for worker_branch_tools.generated.go")
	check := flags.Bool("check", false, "exit 1 if output is stale")
	if err := flags.Parse(args); err != nil {
		return err
	}
	if *outGo == "" {
		return fmt.Errorf("--out-go is required")
	}

	cfg, err := nativemanifest.Load()
	if err != nil {
		return err
	}
	known := func(tool string) bool {
		if cfg.HasTool(tool) {
			return true
		}
		_, ok := cfg.Reversibility(tool)
		return ok
	}
	if err := cfg.ValidateRequiresWorkerBranch(known); err != nil {
		return err
	}
	body := renderGo(cfg.WorkerBranchTools())

	if *check {
		existing, err := os.ReadFile(*outGo) // #nosec G304 -- path from Taskfile
		if err != nil || string(existing) != string(body) {
			return fmt.Errorf("stale %s — run ./task codegen:worker-branch-tools", *outGo)
		}
		_, err = fmt.Fprintln(stdout, "worker-branch-tools codegen OK")
		return err
	}

	if err := os.MkdirAll(filepath.Dir(*outGo), 0o750); err != nil {
		return err
	}
	if err := os.WriteFile(*outGo, body, 0o600); err != nil { // #nosec G306 -- generated artifact
		return err
	}
	_, err = fmt.Fprintln(stdout, "wrote", *outGo)
	return err
}

func renderGo(tools []string) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by codegen-worker-branch-tools. DO NOT EDIT.\n\n")
	b.WriteString("package tools\n\n")
	b.WriteString("// workerBranchTools are native tools that require a private write-worker\n")
	b.WriteString("// branch before Run (pack native-tools.yaml requires_worker_branch).\n")
	b.WriteString("var workerBranchTools = []string{\n")
	for _, tool := range tools {
		b.WriteString("\t")
		b.WriteString(strconv.Quote(tool))
		b.WriteString(",\n")
	}
	b.WriteString("}\n")
	return b.Bytes()
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
