// corpusRead is the read Den folds: a chat's bootstrap before and after the
// events that change it.
const corpusRead = "getSessionBootstrap"

// corpusRecorder keeps the first and the latest answer of one read for the
// resource its first answer read; safe for concurrent use.
type corpusRecorder struct {
	read          string
	mu            sync.Mutex
	first, latest *openapi.CorpusExchange
}

func newCorpusRecorder(read string) *corpusRecorder { return &corpusRecorder{read: read} }

// record keeps a validated success of the recorder's read.
func (c *corpusRecorder) record(ex conformanceExchange) {
	if ex.req.op.ID != c.read || ex.status/100 != 2 || !json.Valid(ex.body) {
		return
	}
	entry := openapi.CorpusExchange{
		Operation: ex.req.op.ID, Method: ex.req.op.Method, Path: ex.req.op.Path,
		Params: ex.req.params, Status: ex.status, ContentType: ex.header.Get("Content-Type"), Body: compactJSON(ex.body),
	}
	c.mu.Lock()
	defer c.mu.Unlock()
	switch {
	case c.first == nil:
		c.first, c.latest = &entry, &entry
	case maps.Equal(c.first.Params, entry.Params):
		c.latest = &entry
	}
}

// corpus is the chat's bootstraps and the envelopes Den replays: the
// bootstraps' cursor boundaries, the chat's message events between them, and
// the first envelope of each topic and payload shape.
func (c *corpusRecorder) corpus(events []wire.EventEnvelope) openapi.HostCorpus {
	c.mu.Lock()
	defer c.mu.Unlock()
	out := openapi.HostCorpus{
		Generated: "Generated by TestAPIConformance (lycaon/test/security/sweeps). Do not edit; refresh with " + openapi.HostCorpusRefresh,
	}
	var first, last corpusBootstrap
	if c.first != nil {
		out.Exchanges = append(out.Exchanges, *c.first)
		first = bootstrapOf(c.first.Body)
		last = first
		if !bytes.Equal(c.first.Body, c.latest.Body) {
			out.Exchanges = append(out.Exchanges, *c.latest)
			last = bootstrapOf(c.latest.Body)
		}
	}
	start, end := -1, -1
	for i, env := range events {
		switch env.Cursor {
		case first.cursor:
			start = i
		case last.cursor:
			end = i
		}
	}
	seen := map[string]bool{}
	for i, env := range events {
		variant := string(env.Topic) + " " + strings.Join(slices.Sorted(maps.Keys(jsonShape(env.Data))), ",")
		boundary := i == start || i == end
		folded := env.Topic == wire.EventTopicMessage && env.Scope.SessionID == first.session && i > start && i <= end
		if boundary || folded || !seen[variant] {
			out.Events = append(out.Events, env)
		}
		seen[variant] = true
	}
	return out
}

// corpusBootstrap is what the corpus needs from a bootstrap answer.
type corpusBootstrap struct{ cursor, session string }

func bootstrapOf(body json.RawMessage) corpusBootstrap {
	var boot struct {
		EventCursor string `json:"event_cursor"`
		Session     struct {
			ID string `json:"id"`
		} `json:"session"`
	}
	_ = json.Unmarshal(body, &boot)
	return corpusBootstrap{cursor: boot.EventCursor, session: boot.Session.ID}
}

func compactJSON(raw []byte) json.RawMessage {
	var out bytes.Buffer
	if json.Compact(&out, raw) != nil {
		return nil
	}
	return out.Bytes()
}

// checkCorpus compares the corpus this sweep observed with the committed one
// by shape: which exchanges and topics exist and the JSON paths each carries.
// Values differ from run to run; a shape change is a wire change Den must see.
func (s *conformanceSweep) checkCorpus(observed openapi.HostCorpus, committedPath string, refresh bool) {
	if refresh {
		raw, err := json.MarshalIndent(observed, "", " ")
		if err == nil {
			err = os.MkdirAll(filepath.Dir(committedPath), 0o755)
		}
		if err == nil {
			err = os.WriteFile(committedPath, append(raw, '\n'), 0o644)
		}
		if err != nil {
			s.findings.add(ruleCorpusIsCurrent, "sweep", "corpus", "could not write %s: %v", openapi.HostCorpusPath, err)
		}
		return
	}
	raw, err := os.ReadFile(committedPath)
	var committed openapi.HostCorpus
	if err == nil {
		err = json.Unmarshal(raw, &committed)
	}
	if err != nil {
		s.findings.add(ruleCorpusIsCurrent, "sweep", "corpus", "could not read %s: %v; refresh with %s", openapi.HostCorpusPath, err, openapi.HostCorpusRefresh)
		return
	}
	for _, diff := range corpusShapeDiff(committed, observed) {
		s.findings.add(ruleCorpusIsCurrent, diff.subject, "corpus", "%s; refresh with %s", diff.detail, openapi.HostCorpusRefresh)
	}
}

type shapeDiff struct{ subject, detail string }

// corpusShapeDiff lists every exchange and topic whose shape differs.
func corpusShapeDiff(committed, observed openapi.HostCorpus) []shapeDiff {
	var diffs []shapeDiff
	compare := func(subject string, was, now map[string]string) {
		switch {
		case was == nil:
			diffs = append(diffs, shapeDiff{subject, "is new to the host"})
		case now == nil:
			diffs = append(diffs, shapeDiff{subject, "is no longer observed"})
		default:
			if path, ok := firstShapeDifference(was, now); ok {
				diffs = append(diffs, shapeDiff{subject, fmt.Sprintf("%s was %q, is now %q", path, was[path], now[path])})
			}
		}
	}
	was, now := exchangeShapes(committed), exchangeShapes(observed)
	for _, key := range slices.Sorted(maps.Keys(union(was, now))) {
		compare(key, was[key], now[key])
	}
	was, now = eventShapes(committed.Events), eventShapes(observed.Events)
	for _, key := range slices.Sorted(maps.Keys(union(was, now))) {
		compare(key, was[key], now[key])
	}
	return diffs
}

func union(a, b map[string]map[string]string) map[string]bool {
	out := map[string]bool{}
	for key := range a {
		out[key] = true
	}
	for key := range b {
		out[key] = true
	}
	return out
}

// exchangeShapes keys each exchange by its operation and answer.
func exchangeShapes(c openapi.HostCorpus) map[string]map[string]string {
	out := map[string]map[string]string{}
	for _, ex := range c.Exchanges {
		key := fmt.Sprintf("%s %d", ex.Operation, ex.Status)
		if out[key] == nil {
			out[key] = map[string]string{}
		}
		maps.Copy(out[key], jsonShape(ex.Body))
	}
	return out
}

// eventShapes unions the payload shapes of each topic.
func eventShapes(envelopes []wire.EventEnvelope) map[string]map[string]string {
	out := map[string]map[string]string{}
	for _, env := range envelopes {
		key := "event " + string(env.Topic)
		if out[key] == nil {
			out[key] = map[string]string{}
		}
		maps.Copy(out[key], jsonShape(env.Data))
	}
	return out
}

// jsonShape maps every JSON path in raw to the kinds of value found there.
// Array members share one path; an empty array contributes only itself.
func jsonShape(raw json.RawMessage) map[string]string {
	shape := map[string]string{}
	if len(raw) == 0 {
		return shape
	}
	var value any
	if json.Unmarshal(raw, &value) != nil {
		shape["$"] = "invalid"
		return shape
	}
	addShape(shape, "$", value)
	return shape
}

func addShape(shape map[string]string, path string, value any) {
	kind := "null"
	switch v := value.(type) {
	case map[string]any:
		kind = "object"
		for key, field := range v {
			// A map keyed by ids has one shape whatever ids a run made.
			if uuid.Validate(key) == nil {
				key = "{id}"
			}
			addShape(shape, path+"."+key, field)
		}
	case []any:
		kind = "array"
		for _, item := range v {
			addShape(shape, path+"[]", item)
		}
	case string:
		kind = "string"
	case float64:
		kind = "number"
	case bool:
		kind = "boolean"
	}
	kinds := strings.Split(shape[path], "|")
	if shape[path] == "" {
		kinds = nil
	}
	if !slices.Contains(kinds, kind) {
		kinds = append(kinds, kind)
		sort.Strings(kinds)
	}
	shape[path] = strings.Join(kinds, "|")
}

// firstShapeDifference names the first path both recordings carry whose
// value kinds share nothing. A path one run lacks, or saw only as null, is an
// optional field the run's data left out, not a wire change; the contract
// test catches a field the contract no longer declares.
func firstShapeDifference(was, now map[string]string) (string, bool) {
	for _, path := range slices.Sorted(maps.Keys(was)) {
		before, after := valueKinds(was[path]), valueKinds(now[path])
		if len(before) > 0 && len(after) > 0 && !slices.ContainsFunc(before, func(kind string) bool { return slices.Contains(after, kind) }) {
			return path, true
		}
	}
	return "", false
}

// valueKinds is a shape entry's kinds other than null.
func valueKinds(entry string) []string {
	var kinds []string
	for _, kind := range strings.Split(entry, "|") {
		if kind != "" && kind != "null" {
			kinds = append(kinds, kind)
		}
	}
	return kinds
}
