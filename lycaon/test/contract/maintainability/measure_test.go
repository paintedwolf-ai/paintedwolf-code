func writeFixture(t *testing.T, root string, files map[string]string) {
	t.Helper()
	for relative, body := range files {
		full := filepath.Join(root, relative)
		testutil.FailErr(t, "create fixture directory", os.MkdirAll(filepath.Dir(full), 0o755))
		testutil.FailErr(t, "write fixture", os.WriteFile(full, []byte(body), 0o644))
	}
}

func TestMaintainabilitySourceClassification(t *testing.T) {
	for _, relative := range []string{"feature/main.go", "feature/generated.go", "feature/handwritten.generated.ts"} {
		if excludedPath(relative) {
			t.Errorf("handwritten path excluded: %s", relative)
		}
	}
	for _, relative := range []string{"third_party/library/main.go", "lycaon/config/runtime/scanners/rules/vendor/rule.py", "feature/testdata/broken.go", "lycaon/test/fixtures/project/main.ts"} {
		if !excludedPath(relative) {
			t.Errorf("vendor or fixture path included: %s", relative)
		}
	}
	for _, relative := range []string{"feature/main_test.go", "lycaon/internal/scan/testfixture/advisory.go", "lycaon/test/contract/support.go", "lycaon/pkg/testcorpus/go.go", "scripts/test_execution.py", "scripts/verification_tests/support.py", "lycaon-den/src-tauri/src/sidecar/tests.rs", "feature/main.test.ts", "feature/curator_testsupport.go"} {
		if !testPath(relative) {
			t.Errorf("test classified as production: %s", relative)
		}
	}
	for _, relative := range []string{"feature/main.go", "feature/Test.tsx", "scripts/test-execution.py"} {
		if testPath(relative) {
			t.Errorf("production classified as test: %s", relative)
		}
	}
}

func TestMaintainabilityGeneratedOutputsRequireGeneratorDeclaration(t *testing.T) {
	root := t.TempDir()
	writeFixture(t, root, map[string]string{
		"Taskfile.yml":                             "tasks:\n  codegen:example:\n    dir: '{{.GO_DIR}}'\n    generates:\n      - internal/generated.go\n  check:\n    generates:\n      - lycaon/internal/handwritten.generated.go\n",
		"lycaon/internal/generated.go":             "package p\n",
		"lycaon/internal/handwritten.generated.go": "// Code generated by pretend. DO NOT EDIT.\npackage p\n",
		"docs/openapi/vocab/Thing.yaml":            "name: ThingKind\n",
	})
	generated, err := generatedOutputs(root)
	testutil.FailErr(t, "read generated outputs", err)
	if !generated["lycaon/internal/generated.go"] || !generated["lycaon/pkg/api/thing_kind_ids.generated.go"] {
		t.Fatalf("generator outputs missing: %v", generated)
	}
	if generated["lycaon/internal/handwritten.generated.go"] {
		t.Fatal("filename or claimed generated header exempted handwritten source")
	}
}

func TestMaintainabilityCodeBearingLines(t *testing.T) {
	for _, fixture := range []struct {
		language, body string
		lines          int
	}{
		{"go", "package p\n// comment\nvar value = `first\n\n// literal\nlast` // trailing\n", 5},
		{"typescript", "// comment\nconst value = `first\n\n// literal\nlast`; /* trailing */\n", 4},
		{"tsx", "// comment\nconst value = <div>text</div>;\n", 1},
		{"javascript", "/* comment\ncomment */\nconst value = '// literal';\n", 1},
		{"python", "# comment\nvalue = '''first\n\n# literal\nlast'''\n", 4},
		{"rust", "// comment\nconst VALUE: &str = r#\"first\n\n// literal\nlast\"#;\n", 4},
		{"bash", "#!/usr/bin/env bash\n# comment\nprintf '%s\\n' '# literal'\n", 1},
	} {
		t.Run(fixture.language, func(t *testing.T) {
			src := source{Path: "fixture", Language: fixture.language, Body: []byte(fixture.body), Test: true}
			inv, err := measure(t.Context(), t.TempDir(), []source{src})
			testutil.FailErr(t, "measure code-bearing lines", err)
			if got := inv.measured["test_files"]["fixture"]; got != fixture.lines {
				t.Fatalf("code-bearing lines = %d, want %d", got, fixture.lines)
			}
		})
	}
}

