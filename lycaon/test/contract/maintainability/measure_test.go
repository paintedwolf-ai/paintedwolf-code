func TestMaintainabilityLocalDependencies(t *testing.T) {
	root := t.TempDir()
	writeFixture(t, root, map[string]string{"feature/one.ts": "", "feature/two/index.ts": "", "feature/three.ts": "", "feature/types.ts": ""})
	src := source{Path: "feature/main.ts", Language: "typescript", Body: []byte(`
import { one } from './one';
import type { Type } from './types';
export { two } from './two';
export * from './one';
const deferred = import('./three');
const repeated = import('./one.ts');
import { external } from 'package';
const misleading = "import('./missing')";
// import('./missing')
`)}
	_, got, err := measureTree(t.Context(), root, src)
	testutil.FailErr(t, "measure local dependencies", err)
	want := map[string]bool{"feature/one.ts": true, "feature/three.ts": true, "feature/two/index.ts": true, "feature/types.ts": true}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("local dependencies = %v, want %v", got, want)
	}
	src.Body = []byte("export * from './missing';")
	if _, _, err := measureTree(t.Context(), root, src); err == nil {
		t.Fatal("unresolved local dependency passed")
	}
}

func TestMaintainabilityGoTypesAggregateAcrossFiles(t *testing.T) {
	sources := []source{
		{Path: "feature/linux.go", Language: "go", Body: []byte("//go:build linux\n\npackage feature\nfunc (m *Manager) Platform() {}\n")},
		{Path: "feature/other.go", Language: "go", Body: []byte("//go:build !linux\n\npackage feature\nfunc (m *Manager) Platform() {\n\t_ = m\n}\n")},
		{Path: "feature/types.go", Language: "go", Body: []byte("package feature\ntype Manager struct { A, B int; *Embedded }\ntype Embedded struct{}\nfunc (m *Manager) Common() {}\n")},
	}
	want := map[string]map[string]int{
		"go_struct_fields":    {"feature/feature.Manager": 3, "feature/feature.Embedded": 0},
		"go_receiver_methods": {"feature/feature.Manager": 2},
		"go_receiver_lines":   {"feature/feature.Manager": 5},
		"source_directories":  {"feature": 3},
	}
	inv, err := measure(t.Context(), t.TempDir(), sources)
	testutil.FailErr(t, "aggregate receivers", err)
	for name, artifacts := range want {
		if !reflect.DeepEqual(inv.measured[name], artifacts) {
			t.Errorf("%s = %v, want %v", name, inv.measured[name], artifacts)
		}
	}
	if files := inv.sources["feature/feature.Manager"]; !reflect.DeepEqual(files, []string{"feature/linux.go", "feature/other.go", "feature/types.go"}) {
		t.Errorf("Manager sources = %v", files)
	}
	sources[0].Path = "feature/relocated.go"
	moved, err := measure(t.Context(), t.TempDir(), sources)
	testutil.FailErr(t, "measure relocated method", err)
	if !reflect.DeepEqual(moved.measured["go_receiver_lines"], inv.measured["go_receiver_lines"]) {
		t.Fatal("moving a method between files changed its type's measurement")
	}
}
