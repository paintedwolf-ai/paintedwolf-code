package contract

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	contractcheck "github.com/lycaon/lycaon/test/contract/internal/check"
)

const denTypesCodegenMarker = "GENERATED by ./task codegen:den-types — DO NOT EDIT"

// Den wire types.ts is codegen-only, with no hand mirror beside it.
func TestDenTypesCodegenGreenfield(t *testing.T) {
	t.Parallel()
	root := contractcheck.RepoRoot(t)
	apiDir := filepath.Join(root, "lycaon-den", "src", "api")

	typesPath := filepath.Join(apiDir, "types.ts")
	data, err := os.ReadFile(typesPath)
	contractcheck.FailErr(t, "read lycaon-den/src/api/types.ts", err)
	text := string(data)
	if !strings.Contains(text, denTypesCodegenMarker) {
		t.Fatalf("types.ts missing codegen header %q — regenerate with ./task codegen:den-types; never hand-edit wire DTOs", denTypesCodegenMarker)
	}
	// Codegen post-processing emits flat schema aliases.
	if !strings.Contains(text, `export type Session = components["schemas"]["Session"]`) {
		t.Fatal(`types.ts missing flat export type Session = components["schemas"]["Session"] — hand mirror or stale codegen`)
	}

	entries, err := os.ReadDir(apiDir)
	contractcheck.FailErr(t, "read lycaon-den/src/api", err)
	var typeTSFiles []string
	for _, ent := range entries {
		name := ent.Name()
		if name == "types.ts" {
			continue
		}
		if strings.HasPrefix(name, "types") && strings.HasSuffix(name, ".ts") && !strings.HasSuffix(name, ".test.ts") {
			typeTSFiles = append(typeTSFiles, name)
		}
	}
	if len(typeTSFiles) > 0 {
		t.Fatalf("forbid extra hand wire type mirrors beside types.ts: %v", typeTSFiles)
	}
}
