// Each shell operand of the condition vocabulary is a closed copy of the
// Den declaration the evaluator binds.
func contributionVocabulariesMatchDen(r *invariants.Run) {
	for _, tc := range []struct {
		goVar, source string
		extract       func(string) ([]string, error)
	}{
		{"focusRegions", "lycaon-den/src/shortcuts/focus-region.ts", func(c string) ([]string, error) { return tsConstStringArray(c, "FOCUS_REGION_IDS") }},
		{"workspaceKinds", "lycaon-den/src/shortcuts/peer-view-subject.ts", func(c string) ([]string, error) { return tsStringUnion(c, "WorkspaceKind") }},
		{"contextFeatures", "lycaon-den/shared/app-state-types.ts", func(c string) ([]string, error) { return tsConstStringArray(c, "CONTEXT_NAV_CATALOG") }},
		{"settingsSections", "lycaon-den/src/settings/settings-nav-model.ts", func(c string) ([]string, error) { return tsStringUnion(c, "SettingsSection") }},
	} {
		den, err := tc.extract(r.Text(tc.source))
		must(r, "read "+tc.source, err)
		r.Diff(tc.goVar+" Go vs Den", mapStringKeys(r, tc.goVar), den)
	}
}

// mapStringKeys returns the string keys of a package-level map literal in
// the contribution vocabulary.
func mapStringKeys(r *invariants.Run, name string) []string {
	f := r.GoFile(contributionVocabulary)
	for _, decl := range f.AST.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.VAR {
			continue
		}
		for _, s := range gen.Specs {
			value, ok := s.(*ast.ValueSpec)
			if !ok || len(value.Names) != 1 || value.Names[0].Name != name || len(value.Values) != 1 {
				continue
			}
			lit, ok := value.Values[0].(*ast.CompositeLit)
			if !ok {
				r.Fatalf("%s is not a composite literal", name)
			}
			var keys []string
			for _, elt := range lit.Elts {
				kv, ok := elt.(*ast.KeyValueExpr)
				basic, isLit := kv.Key.(*ast.BasicLit)
				if !ok || !isLit || basic.Kind != token.STRING {
					r.Fatalf("%s has a key that is not a string literal", name)
				}
				key, err := strconv.Unquote(basic.Value)
				must(r, "unquote a key of "+name, err)
				keys = append(keys, key)
			}
			return keys
		}
	}
	r.Fatalf("var %s not found in %s", name, contributionVocabulary)
	return nil
}

// tsConstStringArray extracts `export const NAME = ["a", "b"] as const`.
func tsConstStringArray(content, name string) ([]string, error) {
	m := regexp.MustCompile(`(?s)export const ` + regexp.QuoteMeta(name) + `[^=]*=\s*\[(.*?)\]`).FindStringSubmatch(content)
	if m == nil {
		return nil, fmt.Errorf("const array %s not found", name)
	}
	var out []string
	for _, v := range regexp.MustCompile(`"([^"]+)"`).FindAllStringSubmatch(m[1], -1) {
		out = append(out, v[1])
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("const array %s is empty", name)
	}
	return out, nil
}

// tsStringUnion extracts `export type Name = "a" | "b"`.
func tsStringUnion(content, name string) ([]string, error) {
	m := regexp.MustCompile(`(?s)export type ` + regexp.QuoteMeta(name) + `\s*=\s*(.*?);`).FindStringSubmatch(content)
	if m == nil {
		return nil, fmt.Errorf("type union %s not found", name)
	}
	var out []string
	for _, seg := range strings.Split(m[1], "|") {
		seg = strings.TrimSpace(seg)
		if seg == "" {
			continue
		}
		if !strings.HasPrefix(seg, `"`) || !strings.HasSuffix(seg, `"`) {
			return nil, fmt.Errorf("type %s has a non-literal member %q", name, seg)
		}
		out = append(out, strings.Trim(seg, `"`))
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("type union %s is empty", name)
	}
	return out, nil
}

// Den's wire types come only from codegen: the generated file carries its
// marker and flat aliases, and no hand mirror sits beside it.
func denTypesAreGeneratedOnly(r *invariants.Run) {
	text := r.Text(denTypesPath)
	if !strings.Contains(text, denTypesMarker) {
		r.Report("%s lacks %q; regenerate with ./task codegen:den-types", denTypesPath, denTypesMarker)
	}
	if !strings.Contains(text, `export type Session = components["schemas"]["Session"]`) {
		r.Report("%s lacks the flat Session alias codegen emits", denTypesPath)
	}
	for _, path := range r.Glob("lycaon-den/src/api/types*.ts") {
		if path != denTypesPath && !strings.HasSuffix(path, ".test.ts") {
			r.Report("%s mirrors wire types by hand beside %s", path, denTypesPath)
		}
	}
}

type apiErrorVocabEntry struct {
	ID     string
	Status []int
	Keys   []string
}

func apiErrorVocab(r *invariants.Run) []apiErrorVocabEntry {
	var doc struct {
		Values []yaml.Node `yaml:"values"`
	}
	must(r, "decode "+apiErrorVocabPath, yaml.Unmarshal(r.Bytes(apiErrorVocabPath), &doc))
	r.Expect(len(doc.Values), apiErrorVocabPath+" values")
	out := make([]apiErrorVocabEntry, 0, len(doc.Values))
	for _, node := range doc.Values {
		var entry apiErrorVocabEntry
		for i := 0; i+1 < len(node.Content); i += 2 {
			key, val := node.Content[i].Value, node.Content[i+1]
			entry.Keys = append(entry.Keys, key)
			switch key {
			case "id":
				entry.ID = val.Value
			case "status":
				status, err := strconv.Atoi(val.Value)
				must(r, "parse the status of "+entry.ID, err)
				entry.Status = append(entry.Status, status)
			}
		}
		out = append(out, entry)
	}
	return out
}

// Each code maps to exactly one error status, the generated lookup agrees,
// a 404 is named for its resource, and retired codes are deleted.
func apiErrorCodesMapToOneStatus(r *invariants.Run) {
	vocab := apiErrorVocab(r)
	for _, entry := range vocab {
		if len(entry.Status) != 1 {
			r.Report("%s declares %d statuses; exactly one is required", entry.ID, len(entry.Status))
			continue
		}
		status := entry.Status[0]
		if status < 400 || status > 599 {
			r.Report("%s declares non-error status %d", entry.ID, status)
		}
		if got := wire.ApiErrorCode(entry.ID).HTTPStatus(); got != status {
			r.Report("%s: generated HTTPStatus() = %d, the vocabulary says %d", entry.ID, got, status)
		}
		if status == 404 && entry.ID != "not_found" && !strings.HasSuffix(entry.ID, "_not_found") {
			r.Report("%s answers 404 but is not named <resource>_not_found", entry.ID)
		}
		for _, key := range entry.Keys {
			if key == "deprecated" || key == "successor" {
				r.Report("%s carries %s; retired codes are deleted, not deprecated", entry.ID, key)
			}
		}
	}
	if len(vocab) != len(wire.AllApiErrorCodeValues()) {
		r.Report("the vocabulary lists %d codes but Go declares %d", len(vocab), len(wire.AllApiErrorCodeValues()))
	}
}

var snakeCode = regexp.MustCompile(`^[a-z][a-z0-9]*(_[a-z0-9]+)*$`)

func apiErrorCodesAreSnakeCase(r *invariants.Run) {
	for _, entry := range apiErrorVocab(r) {
		if !snakeCode.MatchString(entry.ID) {
			r.Report("error code %q is not lowercase snake_case", entry.ID)
		}
	}
}

// The Tauri shell and Den step through the host's startup phases in order;
// Den shows every phase but the terminal ready.
func startupPhasesAgree(r *invariants.Run) {
	var want []string
	for _, phase := range startupprotocol.Phases() {
		want = append(want, string(phase))
	}
	if len(want) == 0 || want[len(want)-1] != "ready" {
		r.Fatalf("the terminal startup phase is not ready: %v", want)
	}
	enum := regexp.MustCompile(`(?s)enum StartupPhase \{(.*?)\n\}`).FindStringSubmatch(r.Text(rustStartupPath))
	if enum == nil {
		r.Fatalf("enum StartupPhase not found in %s", rustStartupPath)
	}
	var rust []string
	for _, v := range regexp.MustCompile(`(?m)^\s+([A-Z][A-Za-z]+),$`).FindAllStringSubmatch(enum[1], -1) {
		rust = append(rust, snakeCase(v[1]))
	}
	if !slices.Equal(rust, want) {
		r.Report("Rust startup phases %v, want %v", rust, want)
	}
	list := regexp.MustCompile(`(?s)ENGINE_STARTUP_PHASES = \[(.*?)\] as const`).FindStringSubmatch(r.Text(tsStartupPath))
	if list == nil {
		r.Fatalf("ENGINE_STARTUP_PHASES not found in %s", tsStartupPath)
	}
	var ts []string
	for _, q := range regexp.MustCompile(`"([a-z_]+)"`).FindAllStringSubmatch(list[1], -1) {
		ts = append(ts, q[1])
	}
	if visible := want[:len(want)-1]; !slices.Equal(ts, visible) {
		r.Report("TypeScript startup phases %v, want %v", ts, visible)
	}
}

func snakeCase(value string) string {
	var out strings.Builder
	for i, c := range value {
		if i > 0 && unicode.IsUpper(c) {
			out.WriteByte('_')
		}
		out.WriteRune(unicode.ToLower(c))
	}
	return out.String()
}

var (
	denProviderIDs = regexp.MustCompile(`export type WebResearchProviderId = (.+);`)
	denCatalogRole = regexp.MustCompile(`(?s)\{\s*id:\s*"([^"]+)"[^}]*roles:\s*\[([^\]]*)\]`)
)

// The generated Den catalog holds the YAML catalog's providers, roles and
// default-enabled flags.
func webResearchCatalogMatchesDen(r *invariants.Run) {
	cat, err := webresearch.LoadCatalog()
	must(r, "load the web research catalog", err)
	den := r.Text(webResearchCatalogPath)
	var ids []string
	if m := denProviderIDs.FindStringSubmatch(den); m != nil {
		for _, part := range strings.Split(m[1], "|") {
			if part = strings.Trim(strings.TrimSpace(part), `"`); part != "" {
				ids = append(ids, part)
			}
		}
	}
	r.Diff("WebResearchProviderId", cat.IDs(), ids)
	roles := map[string][]string{}
	for _, m := range denCatalogRole.FindAllStringSubmatch(den, -1) {
		roles[m[1]] = nil
		for _, part := range strings.Split(m[2], ",") {
			if part = strings.Trim(strings.TrimSpace(part), `"`); part != "" {
				roles[m[1]] = append(roles[m[1]], part)
			}
		}
	}
	for _, entry := range cat.Entries() {
		got, ok := roles[entry.ID]
		if !ok {
			r.Report("WEB_RESEARCH_CATALOG has no entry %s", entry.ID)
			continue
		}
		want := []string{string(webresearch.RoleResults)}
		if len(entry.Roles) > 0 {
			want = nil
			for _, role := range entry.Roles {
				want = append(want, string(role))
			}
		}
		r.Diff(entry.ID+" roles", want, got)
		if entry.DefaultEnabled && !strings.Contains(denEntry(den, entry.ID), "default_enabled: true") {
			r.Report("WEB_RESEARCH_CATALOG entry %s lacks default_enabled: true", entry.ID)
		}
	}
}

func denEntry(ts, id string) string {
	idx := strings.Index(ts, `id: "`+id+`"`)
	if idx < 0 {
		return ""
	}
	start, end := strings.LastIndex(ts[:idx], "{"), strings.Index(ts[idx:], "}")
	if start < 0 || end < 0 {
		return ts[idx:]
	}
	return ts[start : idx+end+1]
}

type eventTopicVocab struct {
	Values []struct {
		ID      string `yaml:"id"`
		Payload string `yaml:"payload"`
	} `yaml:"values"`
}

// docs/schemas/events holds one generated schema per topic, titled and
// referenced from the topic's payload, plus the envelope and generated enums.
func eventSchemasFollowTopics(r *invariants.Run) {
	var vocab eventTopicVocab
	must(r, "decode "+eventTopicVocabPath, yaml.Unmarshal(r.Bytes(eventTopicVocabPath), &vocab))
	r.Expect(len(vocab.Values), "event topics")
	want := []string{"envelope.json", "event-topic.generated.json", "session-status.generated.json"}
	for _, topic := range vocab.Values {
		want = append(want, topic.ID+".json")
		_, payload, ok := strings.Cut(topic.Payload, schemaRefPrefix)
		if !ok {
			r.Report("topic %s has payload ref %q outside %s", topic.ID, topic.Payload, schemaRefPrefix)
			continue
		}
		var schema struct {
			Title string `json:"title"`
			Ref   string `json:"$ref"`
		}
		path := eventSchemasDir + "/" + topic.ID + ".json"
		must(r, "decode "+path, json.Unmarshal(r.Bytes(path), &schema))
		if wantRef := "../../openapi/components/schemas/" + topic.Payload; schema.Title != payload || schema.Ref != wantRef {
			r.Report("%s has title %q and $ref %q, want %q and %q", path, schema.Title, schema.Ref, payload, wantRef)
		}
	}
	var got []string
	for _, path := range r.Glob(eventSchemasDir + "/*.json") {
		got = append(got, strings.TrimPrefix(path, eventSchemasDir+"/"))
	}
	r.Diff("generated event schemas", want, got)
}
