// The config directory names and overlay helpers configdir defines are
// spelled the same in Den, the Tauri shell and the shell scripts.
func configRootNamesMirror(r *invariants.Run) {
	for path, needles := range map[string][]string{
		"lycaon-den/shared/brand.ts": {
			fmt.Sprintf("CONFIG_DIR_NAME = %q", configdir.DirNameProd),
			fmt.Sprintf("CONFIG_DIR_NAME_DEV = %q", configdir.DirNameDev),
		},
		"lycaon-den/src-tauri/src/config_dir.rs": {
			fmt.Sprintf("DIR_NAME_PROD: &str = %q", configdir.DirNameProd),
			fmt.Sprintf("DIR_NAME_DEV: &str = %q", configdir.DirNameDev),
		},
		"scripts/config-dir.sh": {
			configdir.DirNameProd, configdir.DirNameDev,
			"lycaon_config_dir()", "lycaon_channel_config_dir()", "lycaon_overlay_dir()",
			"OVERLAY_FIXTURE_DIR", testutil.OverlayFixtureDirName,
		},
	} {
		text := r.Text(path)
		for _, needle := range needles {
			if !strings.Contains(text, needle) {
				r.Report("%s does not spell %s", path, needle)
			}
		}
	}
}

// Every write declares whether it is recorded as a person's action; reads
// never are.
func operationsDeclarePersonAction(r *invariants.Run) {
	var doc struct {
		Paths map[string]map[string]yaml.Node `yaml:"paths"`
	}
	must(r, "decode paths", spec(r).Decode(&doc))
	for path, item := range doc.Paths {
		for method, node := range item {
			var op struct {
				OperationID  string `yaml:"operationId"`
				PersonAction string `yaml:"x-person-action"`
			}
			if !isOperation(method) {
				continue
			}
			must(r, "decode "+method+" "+path, node.Decode(&op))
			label := strings.ToUpper(method) + " " + path + " (" + op.OperationID + ")"
			switch strings.ToUpper(method) {
			case "GET", "HEAD", "OPTIONS":
				if op.PersonAction != "" {
					r.Report("%s: a read is never recorded as a person action", label)
				}
			default:
				if op.PersonAction != "record" && op.PersonAction != "none" {
					r.Report("%s: declare x-person-action: record or none", label)
				}
			}
		}
	}
}

func isOperation(key string) bool {
	return conventionMethods[key] || key == "head" || key == "options"
}

// hostSchemaBase is the $id base of the host's own JSON schemas.
const hostSchemaBase = "https://lycaon.dev/schemas/host/"

// The live vocabulary export and the committed snapshot both satisfy the
// committed schema, and the snapshot holds every exported entry.
func workflowVocabularyValidates(r *invariants.Run) {
	var schemaDoc any
	must(r, "parse "+vocabularySchemaPath, json.Unmarshal(r.Bytes(vocabularySchemaPath), &schemaDoc))
	compiler := jsonschema.NewCompiler()
	must(r, "add schema", compiler.AddResource(hostSchemaBase+"workflow_vocabulary.schema.json", schemaDoc))
	sch, err := compiler.Compile(hostSchemaBase + "workflow_vocabulary.schema.json")
	must(r, "compile "+vocabularySchemaPath, err)
	entries := vocabularytest.ExportCatalog()
	r.Expect(len(entries), "vocabulary export entries")
	live, err := json.Marshal(map[string]any{"entries": entries})
	must(r, "marshal the export", err)
	committed := r.Bytes(vocabularyCatalogPath)
	for label, raw := range map[string][]byte{"the live export": live, vocabularyCatalogPath: committed} {
		doc, err := jsonschema.UnmarshalJSON(bytes.NewReader(raw))
		must(r, "decode "+label, err)
		if err := sch.Validate(doc); err != nil {
			r.Report("%s does not satisfy %s: %v", label, vocabularySchemaPath, err)
		}
	}
	var snapshot struct {
		Entries []vocabularytest.CatalogEntry `json:"entries"`
	}
	must(r, "decode "+vocabularyCatalogPath, json.Unmarshal(committed, &snapshot))
	if len(snapshot.Entries) != len(entries) {
		r.Report("%s holds %d entries, the export %d; regenerate it", vocabularyCatalogPath, len(snapshot.Entries), len(entries))
	}
}

