#!/usr/bin/env bash
# Generate Den wire types from the bundled OpenAPI schema.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEN="$ROOT/lycaon-den"
OPENAPI="$ROOT/docs/openapi.yaml"
DEST="${1:-}"

usage() {
  echo "usage: $0 DEST" >&2
  exit 2
}

if [[ -z "$DEST" ]]; then
  usage
fi

if [[ ! -f "$OPENAPI" ]]; then
  echo "error: missing $OPENAPI — run ./task openapi:bundle" >&2
  exit 1
fi

BIN="$DEN/node_modules/.bin/openapi-typescript"
if [[ ! -x "$BIN" ]]; then
  echo "error: openapi-typescript not found under lycaon-den/node_modules — run bun install in lycaon-den" >&2
  exit 1
fi

PINNED="$(node -e "const p=require('$DEN/package.json'); process.stdout.write(p.devDependencies['openapi-typescript']||'')")"
INSTALLED="$(node -e "const p=require('$DEN/node_modules/openapi-typescript/package.json'); process.stdout.write(p.version||'')")"
if [[ -z "$PINNED" || "$PINNED" != "$INSTALLED" ]]; then
  echo "error: openapi-typescript version mismatch (package.json=$PINNED installed=$INSTALLED)" >&2
  exit 1
fi

tmp_dir="$(mktemp -d "${TMPDIR:-/tmp}/codegen-den-types.XXXXXX")"
trap 'rm -rf "$tmp_dir"' EXIT
raw="$tmp_dir/raw.ts"
flat="$tmp_dir/flat.ts"

"$BIN" "$OPENAPI" -o "$raw"

node --input-type=module - "$raw" "$flat" <<'NODE'
import { readFileSync, writeFileSync } from "node:fs";

const [, , rawPath, outPath] = process.argv;
const raw = readFileSync(rawPath, "utf8");

const schemaNames = [];
const lines = raw.split("\n");
let inSchemas = false;
for (const line of lines) {
  if (!inSchemas) {
    if (line === "    schemas: {") inSchemas = true;
    continue;
  }
  if (/^    [a-zA-Z]/.test(line)) break; // next components sibling
  const m = /^        ([A-Za-z_][A-Za-z0-9_]*):/.exec(line);
  if (m) schemaNames.push(m[1]);
}

if (schemaNames.length === 0) {
  console.error("error: no components.schemas entries found in openapi-typescript output");
  process.exit(1);
}

const header = `/**
 * GENERATED by ./task codegen:den-types — DO NOT EDIT.
 *
 * Source: docs/openapi.yaml (bundle docs/openapi/** via ./task openapi:bundle).
 * Non-DTO Den helpers compose this file; generated event relations live in
 * event-payloads.generated.ts.
 */

`;

const body = raw.replace(/^\/\*\*[\s\S]*?\*\/\s*/, "");

const aliases = schemaNames
  .map((name) => `export type ${name} = components["schemas"]["${name}"];`)
  .join("\n");

const flatSection = `
// ---------------------------------------------------------------------------
// Flat named exports — call sites import these names directly.
// ---------------------------------------------------------------------------
${aliases}
`;

writeFileSync(outPath, header + body.trimEnd() + "\n" + flatSection);
NODE

mkdir -p "$(dirname "$DEST")"
cp "$flat" "$DEST"
echo "staged $DEST ($(wc -l < "$DEST" | tr -d ' ') lines, schemas=$(grep -c '^export type .* = components\["schemas"\]' "$DEST" || true))"
