"""TB09 · Secret screening and custody (Case families: A10, A11, A13).

Strict D6/D7 discipline:
  - Uses ONLY synthetic run-scoped canaries generated by `wea.canary.CanaryGenerator`.
  - NEVER reads any real developer vault, keychain, or real credentials.
  - NEVER emits raw canary bytes in logs, reports, or receipts (SHA-256 digests only).
"""

from __future__ import annotations

import contextlib
import hashlib
import json
import pathlib
import re
import sys
import uuid
from typing import Any, Iterable

BENCHMARK_DIR = pathlib.Path(__file__).resolve().parent.parent
if str(BENCHMARK_DIR) not in sys.path:
    sys.path.insert(0, str(BENCHMARK_DIR))

from wea.canary import CanaryGenerator, scan_for_canaries
from wea.fixtures_net import RecordingHTTPFixture
from wea.provenance import REPO_ROOT, collect_provenance
from wea.runner import _create_application, _init_git_repo, _open_session, _save_json

REFERENCE_TOKEN_RE = re.compile(
    r"^\{\{paintedwolf-secret:([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})\}\}$"
)

VALID_OUTBOUND_OPTIONS = frozenset({"withhold", "send_redacted", "send_unchanged", "protect"})


def canary_digest(token: str) -> str:
    """Return a D7-safe truncated SHA-256 digest of a synthetic canary token."""
    return hashlib.sha256(token.encode("utf-8")).hexdigest()[:16]


def verify_reference_grammar(token: str) -> dict[str, Any]:
    """Validate canonical `{{paintedwolf-secret:<lowercase-uuid>}}` reference grammar (A11)."""
    stripped = (token or "").strip()
    m = REFERENCE_TOKEN_RE.match(stripped)
    if m:
        return {"valid": True, "malformed": False, "secret_id": m.group(1)}
    has_prefix = "{{paintedwolf-secret:" in stripped
    return {"valid": False, "malformed": has_prefix, "secret_id": None}


def verify_outbound_screening_option(
    option: str,
    endpoint_snapshot: dict[str, Any],
    canary_tokens: Iterable[str],
) -> dict[str, Any]:
    """Verify that a recording HTTP fixture observed the canary ONLY when `option == 'send_unchanged'` (A10).

    Note: `RecordingHTTPFixture` automatically screens bodies/headers matching `redact_tokens`,
    marking `body.redacted == True` when the canary arrived on the wire while keeping the raw
    canary out of the persisted snapshot (D7).
    """
    if option not in VALID_OUTBOUND_OPTIONS:
        raise ValueError(f"unsupported outbound screening option: {option!r}")

    tokens = [t for t in canary_tokens if isinstance(t, str) and t]
    requests = list(endpoint_snapshot.get("requests") or [])
    conn_count = int(endpoint_snapshot.get("connection_count", len(requests)))

    # Ensure raw canary bytes never leaked unredacted into the persisted fixture snapshot itself.
    snapshot_scan = scan_for_canaries(tokens, objects={"endpoint_snapshot": endpoint_snapshot})
    if not snapshot_scan["clean"]:
        return {
            "passed": False,
            "option": option,
            "reason": "raw_canary_in_fixture_snapshot",
            "connection_count": conn_count,
            "canary_wire_hits": 0,
            "snapshot_scan": snapshot_scan,
        }

    wire_canary_hits = 0
    redacted_placeholder_hits = 0
    # SHA-256 prefix of "Bearer [REDACTED]" when RecordingHTTPFixture masks Authorization by header name.
    bearer_redacted_sha_prefix = "<redacted:sha256:cae59a9ed2d6>"
    for req in requests:
        body = req.get("body") or {}
        headers = req.get("headers") or {}
        header_canary_hit = any(
            isinstance(v, str)
            and v.startswith("<redacted:sha256:")
            and v != bearer_redacted_sha_prefix
            and not (isinstance(k, str) and k.lower() == "authorization" and req.get("header_canary_matched") is False)
            for k, v in headers.items()
        )
        if req.get("header_canary_matched") is True or (req.get("header_canary_matched") is None and header_canary_hit):
            wire_canary_hits += 1
        elif body.get("redacted") is True:
            wire_canary_hits += 1
        preview = str(body.get("preview") or "")
        if "[REDACTED]" in preview or "{{paintedwolf-secret:" in preview:
            redacted_placeholder_hits += 1

    if option == "withhold":
        passed = conn_count == 0 and wire_canary_hits == 0
        reason = "ok" if passed else "withheld_option_still_contacted_endpoint"
    elif option == "send_redacted":
        passed = conn_count >= 1 and wire_canary_hits == 0 and redacted_placeholder_hits >= 1
        reason = "ok" if passed else "redacted_option_leaked_or_missing_marker"
    elif option == "protect":
        passed = conn_count >= 1 and wire_canary_hits == 0 and redacted_placeholder_hits >= 1
        reason = "ok" if passed else "protect_option_leaked_or_missing_reference"
    else:  # send_unchanged
        passed = conn_count >= 1 and wire_canary_hits >= 1
        reason = "ok" if passed else "send_unchanged_option_did_not_deliver_canary"

    return {
        "passed": passed,
        "option": option,
        "reason": reason,
        "connection_count": conn_count,
        "canary_wire_hits": wire_canary_hits,
        "redacted_placeholder_hits": redacted_placeholder_hits,
        "snapshot_scan": snapshot_scan,
    }


def audit_stores_for_canaries(
    canaries: Iterable[str],
    *,
    sqlite_dbs: Iterable[str | pathlib.Path] = (),
    log_paths: Iterable[str | pathlib.Path] = (),
    export_paths: Iterable[str | pathlib.Path] = (),
    objects: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Scan every SQLite DB, log, export, and in-memory object for synthetic canary leaks (A10/A11).

    Returns a strictly D7-redacted report containing only truncated SHA-256 digests and locators.
    """
    tokens = [t for t in canaries if isinstance(t, str) and t]
    report = scan_for_canaries(
        tokens,
        paths=[*log_paths, *export_paths],
        sqlite_dbs=sqlite_dbs,
        objects=objects,
    )
    return {
        "clean": bool(report["clean"]),
        "canary_count": int(report["canary_count"]),
        "canary_digests": [canary_digest(t) for t in tokens],
        "scanned_files": int(report["scanned_files"]),
        "scanned_dbs": int(report["scanned_dbs"]),
        "leak_count": int(report["leak_count"]),
        "findings": list(report["findings"]),
    }


def run_tb09_sidecar_suite(
    out_dir: pathlib.Path,
    *,
    engine_bin: str | pathlib.Path | None = None,
    engine_manifest: str | pathlib.Path | None = None,
    engine_root: str | pathlib.Path | None = None,
) -> dict[str, Any]:
    """Run TB09 sidecar custody, project scoping, replace/revoke, and engine-restart checks.

    Drives a real isolated `lycaon-dev` engine (`source_config=None`) and verifies:
      - Creating project secrets never echoes raw canary bytes in API responses.
      - Cross-project secret listing is strictly isolated (A11).
      - Replacing a secret keeps its reference and bumps version; revoking is terminal (A13).
      - Restarting the engine leaves every chat locked and revoked secrets permanently revoked (A13).
      - Scanning `store.db`, `sidecar.log`, and the exported receipt finds zero raw canary leaks (A10/A11).
    """
    out_dir = pathlib.Path(out_dir).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    run_id = f"tb09-{uuid.uuid4().hex[:8]}"
    canaries = CanaryGenerator(run_id)
    canary_v1 = canaries.mint("proj_a_v1")
    canary_v2 = canaries.mint("proj_a_v2")
    canary_b = canaries.mint("proj_b_v1")

    proj_a = out_dir / "project_a"
    proj_b = out_dir / "project_b"
    for p in (proj_a, proj_b):
        p.mkdir(parents=True, exist_ok=True)
        (p / "README.md").write_text("# WEA TB09 fixture\n", encoding="utf-8")
        _init_git_repo(p)

    app_dir = out_dir / "app"
    prov = collect_provenance(REPO_ROOT, engine_bin=engine_bin, engine_manifest=engine_manifest, lane="sidecar")

    observations: dict[str, Any] = {
        "a11_project_scoping": {},
        "a13_lifecycle_and_restart": {},
    }

    # Phase 1: Initial sidecar boot -> create secrets, verify isolation, replace, revoke, lock.
    app = _create_application(app_dir, engine_bin=engine_bin, engine_manifest=engine_manifest, engine_root=engine_root)
    try:
        app.ready()
        sess_a, proj_a_id, _ = _open_session(app, proj_a)
        sess_b, proj_b_id, _ = _open_session(app, proj_b)

        created_a = app.request(
            f"/v1/projects/{proj_a_id}/secrets",
            {
                "operation_id": str(uuid.uuid4()),
                "name": "TB09 Alpha Canary",
                "purpose": "verify custody and project scoping",
                "secret_value": canary_v1,
            },
        )
        created_b = app.request(
            f"/v1/projects/{proj_b_id}/secrets",
            {
                "operation_id": str(uuid.uuid4()),
                "name": "TB09 Beta Canary",
                "purpose": "verify cross-project isolation",
                "secret_value": canary_b,
            },
        )
        ref_a = str(created_a.get("reference") or "")
        ref_b = str(created_b.get("reference") or "")
        ref_a_check = verify_reference_grammar(ref_a)
        ref_b_check = verify_reference_grammar(ref_b)
        secret_a_id = ref_a_check["secret_id"] or ""

        list_a = app.request(f"/v1/projects/{proj_a_id}/secrets")
        list_b = app.request(f"/v1/projects/{proj_b_id}/secrets")
        refs_in_a = {s.get("reference") for s in (list_a.get("secrets") or [])}
        refs_in_b = {s.get("reference") for s in (list_b.get("secrets") or [])}
        observations["a11_project_scoping"] = {
            "ref_a_valid": ref_a_check["valid"],
            "ref_b_valid": ref_b_check["valid"],
            "proj_a_sees_only_own": ref_a in refs_in_a and ref_b not in refs_in_a,
            "proj_b_sees_only_own": ref_b in refs_in_b and ref_a not in refs_in_b,
        }

        # Replace value on secret_a (same reference, version bumps to 2).
        replaced_a = app.request(
            f"/v1/projects/{proj_a_id}/secrets/{secret_a_id}/value",
            {"secret_value": canary_v2},
            method="PUT",
        )
        # Revoke secret_a permanently.
        revoked_a = app.request(
            f"/v1/projects/{proj_a_id}/secrets/{secret_a_id}",
            None,
            method="DELETE",
        )
        # Explicit vault lock call.
        with contextlib.suppress(Exception):
            app.request("/v1/vault/lock", {"reason": "away"})

        observations["a13_lifecycle_and_restart"]["pre_restart"] = {
            "replaced_same_reference": replaced_a.get("reference") == ref_a,
            "replaced_version": replaced_a.get("version"),
            "revoked_state": revoked_a.get("state"),
        }
    finally:
        app.close(cleanup=False)

    # Phase 2: Engine restart on the SAME isolated app_dir -> verify every chat locked & revoked stays revoked.
    app_restarted = _create_application(
        app_dir, engine_bin=engine_bin, engine_manifest=engine_manifest, engine_root=engine_root
    )
    try:
        app_restarted.ready()
        vault_a = app_restarted.request(f"/v1/sessions/{sess_a}/vault")
        vault_b = app_restarted.request(f"/v1/sessions/{sess_b}/vault")
        post_list_a = app_restarted.request(f"/v1/projects/{proj_a_id}/secrets")
        post_a_entry = next(
            (s for s in (post_list_a.get("secrets") or []) if s.get("reference") == ref_a),
            {},
        )
        observations["a13_lifecycle_and_restart"]["post_restart"] = {
            "sess_a_unlocked": bool(vault_a.get("unlocked")),
            "sess_b_unlocked": bool(vault_b.get("unlocked")),
            "revoked_secret_state": post_a_entry.get("state"),
        }
    finally:
        app_restarted.close(cleanup=False)

    # Phase 3: Scan SQLite DB, sidecar logs, and API observations for zero canary leaks.
    audit = audit_stores_for_canaries(
        canaries.tokens,
        sqlite_dbs=[app_dir / "store.db"],
        log_paths=[app_dir / "sidecar.log"],
        objects={"observations": observations},
    )

    passed = (
        audit["clean"]
        and observations["a11_project_scoping"].get("ref_a_valid") is True
        and observations["a11_project_scoping"].get("ref_b_valid") is True
        and observations["a11_project_scoping"].get("proj_a_sees_only_own") is True
        and observations["a11_project_scoping"].get("proj_b_sees_only_own") is True
        and observations["a13_lifecycle_and_restart"]["pre_restart"].get("replaced_same_reference") is True
        and observations["a13_lifecycle_and_restart"]["pre_restart"].get("revoked_state") == "revoked"
        and observations["a13_lifecycle_and_restart"]["post_restart"].get("sess_a_unlocked") is False
        and observations["a13_lifecycle_and_restart"]["post_restart"].get("sess_b_unlocked") is False
        and observations["a13_lifecycle_and_restart"]["post_restart"].get("revoked_secret_state") == "revoked"
    )

    receipt = {
        "schema": "wea-tb09-sidecar-v1",
        "run_id": run_id,
        "case_families": ["A10", "A11", "A13"],
        "provenance": prov,
        "observations": observations,
        "canary_audit": audit,
        "passed": passed,
    }
    receipt_path = out_dir / "tb09_receipt.json"
    _save_json(receipt_path, receipt)

    # Re-scan the written receipt file on disk to guarantee D7 redaction.
    receipt_scan = scan_for_canaries(canaries.tokens, paths=[receipt_path])
    receipt["receipt_file_clean"] = receipt_scan["clean"]
    if not receipt_scan["clean"]:
        receipt["passed"] = False
    return receipt
